// waitForRefExcluding polls fresh snapshots like waitForRef (hotels_search.go),
// but skips any match equal to excludeRef.
//
// CONFIRMED LIVE 2026-09-24: needed because a page-level action button and
// its own confirmation dialog's button can share an identical accessible
// name and role simultaneously. Reproduced on Concur's report-submit flow:
// clicking the report page's "Submit Report" button opens a "Report
// Totals" confirmation dialog that contains a SECOND, separate "Submit
// Report" button (Dialog Actions toolbar, alongside "Cancel") -- while that
// dialog is open, a plain snapshot has BOTH the original page button and
// the dialog's confirm button matching name="Submit Report" role="button"
// at once. findRef/waitForRef alone resolve to whichever ref Go's
// non-deterministic map iteration over agentBrowserSnapshotRefs' return
// value happens to visit first; on an unlucky iteration that re-clicks the
// already-clicked page button instead of ever reaching the dialog's actual
// confirm action, silently failing to submit while reporting no error (the
// click itself succeeds, it is just the wrong element).
func waitForRefExcluding(nameSubstr, role, excludeRef string, timeout time.Duration) (string, error) {
	deadline := time.Now().Add(timeout)
	for {
		refs, err := agentBrowserSnapshotRefs()
		if err != nil {
			return "", err
		}
		lowerSubstr := strings.ToLower(nameSubstr)
		for ref, entry := range refs {
			if ref == excludeRef {
				continue
			}
			if role != "" && entry.Role != role {
				continue
			}
			if strings.Contains(strings.ToLower(entry.Name), lowerSubstr) {
				return ref, nil
			}
		}
		if time.Now().After(deadline) {
			return "", fmt.Errorf("no element matching %q (role %q, excluding ref %s) appeared within %s -- the page structure may have changed", nameSubstr, role, excludeRef, timeout)
		}
		time.Sleep(400 * time.Millisecond)
	}
}

// clearAndFillField robustly replaces a text field's entire value, instead
// of relying on agent-browser's `fill` to always do so.
//
// CONFIRMED LIVE 2026-09-24: on Concur's expense-edit form, plain `fill` on
// the "Business Purpose" textbox APPENDED to the field's existing value
// instead of replacing it -- filling "test-updated-purpose" over an
// existing "test" produced "testtest-updated-purpose", not a clean
// replacement, despite agent-browser's own `fill --help` documenting
// "Clears the input field and fills it with the specified text." The
// Amount field on the same form replaced cleanly with plain `fill` in the
// same session, so this is a per-field/component quirk (most likely the
// Business Purpose textbox is not a plain <input> under the hood), not a
// universal agent-browser bug. Home, then Shift+End, then Backspace
// reliably empties the field first (confirmed: the field showed genuinely
// empty afterward, including tripping Concur's own "missing required
// information" validation), and a `fill` onto an empty field is unambiguous
// regardless of the field's underlying implementation.
//
// Applied unconditionally to every field this fallback edits, not just the
// one field where the append bug was caught live -- there is no
// confirmed-safe way to know in advance which specific fields are affected,
// and the extra keystrokes are cheap insurance against silently corrupting
// a field's value into a concatenation of old and new text.
func clearAndFillField(ref, value string) error {
	if _, err := runAgentBrowser("click", "@"+ref); err != nil {
		return fmt.Errorf("clicking field to clear it: %w", err)
	}
	if _, err := runAgentBrowser("press", "Home"); err != nil {
		return fmt.Errorf("pressing Home to clear field: %w", err)
	}
	if _, err := runAgentBrowser("press", "Shift+End"); err != nil {
		return fmt.Errorf("pressing Shift+End to clear field: %w", err)
	}
	if _, err := runAgentBrowser("press", "Backspace"); err != nil {
		return fmt.Errorf("pressing Backspace to clear field: %w", err)
	}
	if _, err := runAgentBrowser("fill", "@"+ref, value); err != nil {
		return fmt.Errorf("filling field: %w", err)
	}
	return nil
}

var monthNameLookup = map[string]time.Month{
	"January": time.January, "February": time.February, "March": time.March,
	"April": time.April, "May": time.May, "June": time.June,
	"July": time.July, "August": time.August, "September": time.September,
	"October": time.October, "November": time.November, "December": time.December,
}

// readDisplayedCalendarMonth reads Concur's date-picker header (a toolbar
// with a "Previous month" button, an exact-text month-name button, an
// exact-text year button, and a "Next month" button -- confirmed live
// 2026-09-24) to determine which month/year the calendar is currently
// showing. Deliberately does an EXACT name match (not findRef's substring
// match): every calendar day button's own accessible name is a full
// "<Weekday> <Month> <Day>, <Year>" string that also CONTAINS the bare
// month name and year as substrings (e.g. "Tuesday September 15, 2026"
// contains both "September" and "2026") -- a substring search for the
// header's month/year would non-deterministically match whichever day
// button Go's map iteration happened to visit first instead of the header
// itself.
func readDisplayedCalendarMonth(refs map[string]agentBrowserRefEntry) (time.Month, int, error) {
	var monthName string
	var year int
	for _, entry := range refs {
		if entry.Role != "button" {
			continue
		}
		if _, ok := monthNameLookup[entry.Name]; ok {
			monthName = entry.Name
		}
		if y, err := strconv.Atoi(entry.Name); err == nil && y > 2000 && y < 2100 {
			year = y
		}
	}
	if monthName == "" || year == 0 {
		return 0, 0, fmt.Errorf("calendar header month/year buttons not found (found month=%q year=%d) -- Concur's calendar structure may have changed", monthName, year)
	}
	return monthNameLookup[monthName], year, nil
}

// PATCH(amend-2026-11-03: define ClickEarlierAttemptMayHaveLandedError and timeouts)
const navigationPollTimeout = 3 * time.Second

type ClickEarlierAttemptMayHaveLandedError struct {
	Attempt int
	Cause   error
}

func (e *ClickEarlierAttemptMayHaveLandedError) Error() string {
	return fmt.Sprintf("click error on attempt %d: an earlier click may already have landed: %v", e.Attempt, e.Cause)
}

func (e *ClickEarlierAttemptMayHaveLandedError) Unwrap() error {
	return e.Cause
}

// clickWithNavigationRetry clicks initialRef, then retries once against a
// freshly re-found ref (by name/role) if the browser is still showing
// staleURLSubstr afterward.
//
// CONFIRMED LIVE 2026-09-24: a Save Expense click, using a ref captured via
// waitForRef immediately beforehand -- the same pattern already proven
// reliable for same-day expense creation earlier this session -- silently
// failed to navigate away or persist any change on a backdated-expense
// creation attempt, despite every form field showing correct, fully-filled
// values in the very next snapshot (ruling out an unfilled-required-field
// cause). A manual re-click on a freshly re-snapshotted ref for the exact
// same button, moments later, worked and the expense saved correctly (
// verified via the report total increasing by precisely the submitted
// amount, with no duplicate). This points to a timing race -- the click
// firing before some async validation/render triggered by the preceding
// calendar-picker interaction had settled -- rather than a wrong-element
// bug, though the exact mechanism was not fully isolated. One bounded
// retry against a fresh ref is cheap insurance against losing an
// otherwise fully correctly-filled form to this race.
//
// PATCH(amend-2026-11-03: replace sleep with polling, check URL on click errors, return ClickEarlierAttemptMayHaveLandedError)
func clickWithNavigationRetry(initialRef, staleURLSubstr, retryName, retryRole string, timeout time.Duration) error {
	ref := initialRef
	const maxAttempts = 3
	for attempt := 1; attempt <= maxAttempts; attempt++ {
		if _, err := runAgentBrowser("click", "@"+ref); err != nil {
			if attempt >= 2 {
				currentURL, urlErr := agentBrowserCurrentURL()
				if urlErr == nil && !strings.Contains(currentURL, staleURLSubstr) {
					return nil // navigated away already, first click was successful
				}
				return &ClickEarlierAttemptMayHaveLandedError{Attempt: attempt, Cause: err}
			}
			return err
		}

		// Poll for URL change
		pollDeadline := time.Now().Add(navigationPollTimeout)
		var navigated bool
		for time.Now().Before(pollDeadline) {
			currentURL, err := agentBrowserCurrentURL()
			if err == nil && !strings.Contains(currentURL, staleURLSubstr) {
				navigated = true
				break
			}
			time.Sleep(150 * time.Millisecond)
		}
		if navigated {
			return nil
		}

		if attempt == maxAttempts {
			break
		}
		var err error
		ref, err = waitForRef(retryName, retryRole, timeout)
		if err != nil {
			return &ClickEarlierAttemptMayHaveLandedError{
				Attempt: attempt + 1,
				Cause:   fmt.Errorf("click did not navigate away and could not re-find %q to retry (attempt %d/%d): %w", retryName, attempt, maxAttempts, err),
			}
		}
	}
	return &ClickEarlierAttemptMayHaveLandedError{
		Attempt: maxAttempts,
		Cause:   fmt.Errorf("clicked %q %d times but the page never navigated away from a URL containing %q -- the save/submit may not have registered", retryName, maxAttempts, staleURLSubstr),
	}
}

// fillTransactionDate sets Concur's Transaction Date field via its calendar
// picker, navigating month-by-month toward the target date and clicking its
// specific day button, rather than typing into the field directly.
//
// CONFIRMED LIVE 2026-09-24: this field resists ordinary text-clearing in a
// way no other field on this form does. clearAndFillField's Home+Shift+End+
// Backspace sequence left a pre-existing value in place; 25 consecutive
// plain Backspace presses after Click+End did too. A plain `fill` onto that
// non-empty field APPENDED instead of replacing (producing
// "09/24/202609/15/2026" from an existing "09/24/2026" plus a fill of
// "09/15/2026") -- the same failure *category* as Business Purpose's
// append bug (see clearAndFillField's doc comment), just resistant to that
// helper's specific remedy, most likely because this is a masked/formatted
// date component rather than a plain text input. The calendar's day
// buttons, by contrast, have a fully descriptive accessible name
// ("<Weekday> <Month> <Day>, <Year>") and clicking one unambiguously
// REPLACES the field's value regardless of whatever was there before --
// confirmed live by reproducing the append bug, then clicking a day button
// and seeing the field show a clean, correct value with no leftover text.
//
// The calendar's opening month is NOT assumed to be "today" -- confirmed
// elsewhere this session that this exact form can carry stale state across
// same-URL SPA route re-entries, so guessing a fixed navigation direction
// risked navigating the wrong way. Reads the header's actual displayed
// month/year each iteration and steps toward the target instead.
func fillTransactionDate(target time.Time) error {
	if err := ensurePageVisible(); err != nil {
		return err
	}
	var calendarOpened bool
	var lastErr error

	// Try ref-based click with fresh refs, up to 3 attempts
	for attempt := 1; attempt <= 3; attempt++ {
		calendarButtonRef, err := waitForRef("Open calendar", "button", 5*time.Second)
		if err != nil {
			lastErr = fmt.Errorf("could not find Open calendar button on attempt %d: %w", attempt, err)
			continue
		}

		if _, err := runAgentBrowser("click", "@"+calendarButtonRef); err != nil {
			lastErr = fmt.Errorf("clicking Open calendar button on attempt %d: %w", attempt, err)
			continue
		}

		// Poll snapshots (bounded, ~3 s) until readDisplayedCalendarMonth succeeds
		pollDeadline := time.Now().Add(3 * time.Second)
		var opened bool
		for time.Now().Before(pollDeadline) {
			refs, err := agentBrowserSnapshotRefs()
			if err == nil {
				if _, _, err := readDisplayedCalendarMonth(refs); err == nil {
					opened = true
					break
				}
			}
			time.Sleep(200 * time.Millisecond)
		}

		if opened {
			calendarOpened = true
			break
		}
		lastErr = fmt.Errorf("calendar did not open after clicking button on attempt %d (readDisplayedCalendarMonth failed)", attempt)
	}

	if !calendarOpened {
		return fmt.Errorf("all calendar opening strategies failed (tried 3 ref clicks). The Concur page may be hidden or not focused, or Concur's form structure has changed. Prior errors: %v", lastErr)
	}

	dayName := fmt.Sprintf("%s %s %d, %d", target.Weekday(), target.Month(), target.Day(), target.Year())

	// PATCH(Greptile review, "Older expense dates are rejected") -- a fixed
	// 24-step (2-year) bound rejected any genuinely valid date further out
	// than that from wherever the calendar happens to be showing when it
	// opens (which this function's own doc comment above already
	// establishes is NOT reliably "today" -- it can carry stale state from
	// a prior same-URL SPA visit). --date has no policy-driven range limit
	// of its own, so this loop bound must not impose one either. Reads the
	// calendar's own displayed month/year up front and sizes the bound to
	// the ACTUAL distance being navigated (with a small safety margin for
	// the loop's own step-by-step drift), so any real date this session
	// verified live -- weeks, months, or years away -- is reachable, while
	// still bounding a genuinely broken calendar (navigation buttons that
	// stop responding) rather than looping forever.
	initialRefs, err := agentBrowserSnapshotRefs()
	if err != nil {
		return fmt.Errorf("reading initial calendar state: %w", err)
	}
	shownMonth0, shownYear0, err := readDisplayedCalendarMonth(initialRefs)
	if err != nil {
		return err
	}
	monthsAway0 := (target.Year()-shownYear0)*12 + (int(target.Month()) - int(shownMonth0))
	if monthsAway0 < 0 {
		monthsAway0 = -monthsAway0
	}
	maxMonthClicks := monthsAway0 + 3 // small margin for the loop's own re-reads
	if maxMonthClicks < 12 {
		maxMonthClicks = 12 // floor: still bounds a genuinely broken calendar
	}
	for i := 0; i < maxMonthClicks; i++ {
		refs, err := agentBrowserSnapshotRefs()
		if err != nil {
			return fmt.Errorf("reading calendar state: %w", err)
		}
		if ref, ok := findRef(refs, dayName, "button"); ok {
			if _, err := runAgentBrowser("click", "@"+ref); err != nil {
				return fmt.Errorf("clicking calendar day %q: %w", dayName, err)
			}
			return nil
		}
		shownMonth, shownYear, err := readDisplayedCalendarMonth(refs)
		if err != nil {
			return err
		}
		monthsAway := (target.Year()-shownYear)*12 + (int(target.Month()) - int(shownMonth))
		if monthsAway == 0 {
			return fmt.Errorf("calendar shows the target month (%s %d) but no button matched day %q -- Concur's calendar structure may have changed", shownMonth, shownYear, dayName)
		}
		navName := "Next month"
		if monthsAway < 0 {
			navName = "Previous month"
		}
		navRef, ok := findRef(refs, navName, "button")
		if !ok {
			return fmt.Errorf("could not find the %q calendar navigation button", navName)
		}
		if _, err := runAgentBrowser("click", "@"+navRef); err != nil {
			return fmt.Errorf("clicking %q: %w", navName, err)
		}
		time.Sleep(250 * time.Millisecond)
	}
	return fmt.Errorf("could not reach %s in the calendar within %d month-navigation steps -- Concur's calendar structure may have changed", target.Format("2006-01-02"), maxMonthClicks)
}

// PATCH(amend-2026-11-03: wait for either reference excluding the first ref)
//
// names is a priority list: every ref is checked against names[0] before any
// is checked against names[1], so the result does not depend on Go's
// randomized map iteration. That matters for the submit flow: the confirm
// dialog's own button ("Proceed" today) must win over the page-level
// "Submit Report" button, whose ref can change between snapshots and so
// slip past excludeRef.
func waitForEitherRefExcluding(names []string, role, excludeRef string, timeout time.Duration) (string, string, error) {
	deadline := time.Now().Add(timeout)
	for {
		refs, err := agentBrowserSnapshotRefs()
		if err != nil {
			return "", "", err
		}
		for _, nameSubstr := range names {
			lowerSubstr := strings.ToLower(nameSubstr)
			// Sorted so equally-ranked matches resolve the same way every run.
			sortedRefs := make([]string, 0, len(refs))
			for ref := range refs {
				sortedRefs = append(sortedRefs, ref)
			}
			sort.Strings(sortedRefs)
			for _, ref := range sortedRefs {
				entry := refs[ref]
				if ref == excludeRef {
					continue
				}
				if role != "" && entry.Role != role {
					continue
				}
				if strings.Contains(strings.ToLower(entry.Name), lowerSubstr) {
					return ref, nameSubstr, nil
				}
			}
		}
		if time.Now().After(deadline) {
			return "", "", fmt.Errorf("no element matching either %v (role %q, excluding ref %s) appeared within %s -- the page structure may have changed", names, role, excludeRef, timeout)
		}
		time.Sleep(400 * time.Millisecond)
	}
}

// PATCH(amend-2026-11-03: ensure page visibility helpers for when the browser is hidden/minimized)
func getDocumentVisibilityState() (string, error) {
	out, err := runAgentBrowser("eval", "document.visibilityState", "--json")
	if err == nil {
		var env struct {
			Success bool `json:"success"`
			Data    struct {
				Result string `json:"result"`
			} `json:"data"`
		}
		if json.Unmarshal(out, &env) == nil && env.Success {
			return strings.ToLower(strings.Trim(env.Data.Result, `"`)), nil
		}
	}

	out, err = runAgentBrowser("eval", "document.visibilityState")
	if err != nil {
		return "", err
	}
	res := strings.ToLower(strings.TrimSpace(string(out)))
	res = strings.Trim(res, `"'`)
	if res == "visible" || res == "hidden" {
		return res, nil
	}
	return "", fmt.Errorf("unexpected visibility state: %s", res)
}

func getActiveTabID() (string, error) {
	out, err := runAgentBrowser("tab", "list", "--json")
	if err == nil {
		type tabEntry struct {
			Active bool   `json:"active"`
			TabID  string `json:"tabId"`
			ID     string `json:"id"`
			Ref    string `json:"ref"`
			Label  string `json:"label"`
		}
		type tabListEnvelope struct {
			Success bool `json:"success"`
			Data    struct {
				Tabs []tabEntry `json:"tabs"`
			} `json:"data"`
		}
		var env tabListEnvelope
		if json.Unmarshal(out, &env) == nil && env.Success {
			for _, t := range env.Data.Tabs {
				if t.Active {
					if t.TabID != "" {
						return t.TabID, nil
					}
					if t.ID != "" {
						return t.ID, nil
					}
					if t.Ref != "" {
						return t.Ref, nil
					}
					if t.Label != "" {
						return t.Label, nil
					}
				}
			}
		}
	}

	out, err = runAgentBrowser("tab", "list")
	if err != nil {
		return "", err
	}
	lines := strings.Split(string(out), "\n")
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.Contains(trimmed, "→") || strings.Contains(trimmed, "->") || strings.HasPrefix(trimmed, "→") {
			start := strings.Index(trimmed, "[")
			end := strings.Index(trimmed, "]")
			if start != -1 && end != -1 && end > start+1 {
				return trimmed[start+1 : end], nil
			}
		}
	}

	return "", fmt.Errorf("active tab not found")
}

func ensurePageVisible() error {
	const maxPoll = 3 * time.Second
	pollDeadline := time.Now().Add(maxPoll)

	for {
		visibility, err := getDocumentVisibilityState()
		if err != nil {
			return nil
		}
		if visibility == "visible" {
			return nil
		}
		if visibility == "hidden" {
			activeID, tabErr := getActiveTabID()
			if tabErr == nil && activeID != "" {
				_, _ = runAgentBrowser("tab", activeID)
			}
		}

		if time.Now().After(pollDeadline) {
			break
		}
		time.Sleep(250 * time.Millisecond)
	}

	lastVis, err := getDocumentVisibilityState()
	if err == nil && lastVis == "hidden" {
		return fmt.Errorf("the Concur browser window is hidden or minimized; bring it to the front and retry")
	}
	return nil
}

// PATCH(amend-2026-11-03: navigate to page, with tolerant retry on timeout and ensuring visibility)
func openPageTolerant(url, mustContain string) error {
	_, err := runAgentBrowser("open", url)
	var opened bool
	if err == nil {
		opened = true
	} else {
		if strings.Contains(strings.ToLower(err.Error()), "timed out") {
			deadline := time.Now().Add(5 * time.Second)
			for time.Now().Before(deadline) {
				currentURL, urlErr := agentBrowserCurrentURL()
				if urlErr == nil && strings.Contains(currentURL, mustContain) {
					opened = true
					break
				}
				time.Sleep(300 * time.Millisecond)
			}
		}
		if !opened {
			return err
		}
	}

	if err := ensurePageVisible(); err != nil {
		return err
	}
	return nil
}
