const startAirShopMutation = `mutation startFlightShop($searchCriteria: TravelAirSearchRequestInput!) {
  travel {
    air {
      startShop(searchCriteria: $searchCriteria) {
        shopId
        tripId
      }
    }
  }
}`

const pollAirShopQuery = `query pollAirShop($id: ID!, $pageSize: Int!) {
  travel {
    air {
      shop(id: $id) {
        id
        status
        selectionSetV2 {
          journeyPage(size: $pageSize) {
            data {
              totalElements
              content {
                origin { iataCode name }
                destination { iataCode name }
                marketingCarrier { name iataCode }
                departureDateTime
                arrivalDateTime
                duration
                nonstop
                offers {
                  amount {
                    total {
                      amount
                      currencyCode
                    }
                  }
                  policyCompliance {
                    violationLevel
                  }
                }
              }
            }
          }
        }
      }
    }
  }
}`

type flightStartShopGQLEnvelope struct {
	Data struct {
		Travel struct {
			Air struct {
				StartShop struct {
					ShopID string `json:"shopId"`
					TripID string `json:"tripId"`
				} `json:"startShop"`
			} `json:"air"`
		} `json:"travel"`
	} `json:"data"`
	Errors []gqlErrorEntry `json:"errors"`
}

type flightPollShopGQLEnvelope struct {
	Data struct {
		Travel struct {
			Air struct {
				Shop struct {
					ID             string `json:"id"`
					Status         string `json:"status"`
					SelectionSetV2 struct {
						JourneyPage struct {
							Data struct {
								TotalElements int               `json:"totalElements"`
								Content       []json.RawMessage `json:"content"`
							} `json:"data"`
						} `json:"journeyPage"`
					} `json:"selectionSetV2"`
				} `json:"shop"`
			} `json:"air"`
		} `json:"travel"`
	} `json:"data"`
	Errors []gqlErrorEntry `json:"errors"`
}

// airLocationTypeFor maps a locationSuggestions __typename to the enum
// TravelAirOriginDestinationInput expects.
func airLocationTypeFor(typename string) string {
	switch typename {
	case "TravelAirAirportLocation":
		return "AIRPORT"
	case "TravelAirPlaceLocation":
		return "PLACE"
	case "TravelAirCompanyLocation":
		return "COMPANY_LOCATION"
	case "TravelAirCompanyHubLocation":
		return "COMPANY_HUB"
	case "TravelAirRailStationLocation":
		return "RAIL_STATION"
	default:
		return "AIRPORT"
	}
}

type resolvedFlightLocation struct {
	id      string
	locType string
	name    string
}

// resolveOneFlightLocation looks up the first locationSuggestions match for
// a free-text query (city, airport name, or IATA code) and returns its id
// and the location-type enum value TravelAirOriginDestinationInput expects.
// Reuses the same query flights_locations.go exposes directly.
func resolveOneFlightLocation(cmd *cobra.Command, c *client.Client, flags *rootFlags, query string) (resolvedFlightLocation, error) {
	body := map[string]any{
		"query":     flightLocationSuggestionsQuery,
		"variables": map[string]any{"query": query},
	}
	raw, status, err := c.PostQueryWithParams(cmd.Context(), concurGraphQLPath, map[string]string{}, body)
	if err != nil {
		return resolvedFlightLocation{}, classifyAPIError(err, flags)
	}
	if status < 200 || status >= 300 {
		return resolvedFlightLocation{}, fmt.Errorf("HTTP %d resolving location", status)
	}
	var env flightLocationsGQLEnvelope
	if err := json.Unmarshal(raw, &env); err != nil {
		return resolvedFlightLocation{}, fmt.Errorf("parsing location response: %w", err)
	}
	if len(env.Errors) > 0 {
		return resolvedFlightLocation{}, fmt.Errorf("%s", env.Errors[0].Detail())
	}
	if len(env.Data.Travel.Air.LocationSuggestions) == 0 {
		return resolvedFlightLocation{}, fmt.Errorf("no location matched %q", query)
	}
	var top struct {
		Typename string `json:"__typename"`
		ID       string `json:"id"`
		Name     string `json:"name"`
	}
	if err := json.Unmarshal(env.Data.Travel.Air.LocationSuggestions[0], &top); err != nil {
		return resolvedFlightLocation{}, fmt.Errorf("parsing top location match: %w", err)
	}
	return resolvedFlightLocation{id: top.ID, locType: airLocationTypeFor(top.Typename), name: top.Name}, nil
}

func newFlightsSearchCmd(flags *rootFlags) *cobra.Command {
	var fromQuery, toQuery, departDate, returnDate, cabin string
	var limit int
	var pollTimeout time.Duration

	cmd := &cobra.Command{
		Use:   "search",
		Short: "Search real flight availability and fares (creates a live shopping session -- searches only, never books)",
		Long: `Search flight availability via the same GraphQL BFF the Concur Flight Search
UI uses. This creates a real shopping session on your Concur tenant --
exactly what clicking "Search Flights" does -- but never books or spends
anything.

--from/--to accept free text (city, airport name, or IATA code) and are
resolved via the same lookup as 'flights locations'. Metro queries like
"New York" resolve to the metro as a single search endpoint covering its
constituent airports (JFK/LGA/EWR), not a single specific airport.

KNOWN GAP: when --return is given, only the OUTBOUND leg's flights are
rendered. Combined round-trip fares require a select-then-refine step not
yet implemented -- see 'concur-pp-cli which flights.search --json' or the
patch notes for detail.`,
		Example:     "  concur-pp-cli flights search --from LAX --to NYC --depart 2026-10-12\n  concur-pp-cli flights search --from LAX --to NYC --depart 2026-10-12 --return 2026-10-16",
		Annotations: map[string]string{"pp:endpoint": "flights.search", "pp:method": "POST", "pp:path": "https://www-us2.api.concursolutions.com/cds/graphql", "mcp:read-only": "false"},
		RunE: func(cmd *cobra.Command, args []string) error {
			if fromQuery == "" || toQuery == "" || departDate == "" {
				return usageErr(fmt.Errorf("--from, --to, and --depart are required"))
			}
			if !flags.yes && !flags.dryRun {
				fmt.Fprintf(cmd.ErrOrStderr(), "refusing to create a live flight shopping session for %q -> %q without --yes\n", fromQuery, toQuery)
				return fmt.Errorf("confirmation required: pass --yes (this creates a real session on your Concur tenant, though it books nothing)")
			}

			c, err := flags.newClient()
			if err != nil {
				return err
			}

			// Step 1: resolve --from / --to to location IDs + types. In
			// --dry-run, the client's verify-mode short-circuit intercepts
			// this lookup too (it rides the same GraphQL POST transport as
			// the mutation preview below), so a real resolution failure
			// there is expected, not a bug -- fall back to a clearly-marked
			// placeholder so the dry-run preview can still render, matching
			// the mock-fallback-with-notice convention already established
			// in expenses_tag.go/trips_reconcile.go.
			fromLoc, err := resolveOneFlightLocation(cmd, c, flags, fromQuery)
			if err != nil {
				if !flags.dryRun {
					return fmt.Errorf("resolving --from %q: %w", fromQuery, err)
				}
				fmt.Fprintf(cmd.ErrOrStderr(), "dry-run: could not resolve --from %q live (%v); previewing with a placeholder id\n", fromQuery, err)
				fromLoc = resolvedFlightLocation{id: "<unresolved:" + fromQuery + ">", locType: "AIRPORT", name: fromQuery}
			}
			toLoc, err := resolveOneFlightLocation(cmd, c, flags, toQuery)
			if err != nil {
				if !flags.dryRun {
					return fmt.Errorf("resolving --to %q: %w", toQuery, err)
				}
				fmt.Fprintf(cmd.ErrOrStderr(), "dry-run: could not resolve --to %q live (%v); previewing with a placeholder id\n", toQuery, err)
				toLoc = resolvedFlightLocation{id: "<unresolved:" + toQuery + ">", locType: "AIRPORT", name: toQuery}
			}

			// Step 2: build originDestinations (1 or 2 legs) and searchType.
			originDestinations := []map[string]any{
				{
					"originLocationId":        fromLoc.id,
					"originLocationType":      fromLoc.locType,
					"destinationLocationId":   toLoc.id,
					"destinationLocationType": toLoc.locType,
					"departureDate":           departDate,
				},
			}
			searchType := "ONE_WAY"
			if returnDate != "" {
				searchType = "ROUND_TRIP"
				originDestinations = append(originDestinations, map[string]any{
					"originLocationId":        toLoc.id,
					"originLocationType":      toLoc.locType,
					"destinationLocationId":   fromLoc.id,
					"destinationLocationType": fromLoc.locType,
					"departureDate":           returnDate,
				})
			}
			searchCriteria := map[string]any{
				"searchType":         searchType,
				"originDestinations": originDestinations,
			}
			if cabin != "" {
				searchCriteria["preferredCabinType"] = cabin
			}

			if flags.dryRun {
				// Human-readable note goes to stderr, matching the --from/--to
				// resolution notices above -- stdout carries only the JSON
				// preview (with dry_run:true folded in, matching the
				// generated commands' envelope convention) so --json output
				// stays valid, parseable JSON instead of prose-plus-JSON.
				preview := map[string]any{
					"mutation":  "startShop",
					"variables": map[string]any{"searchCriteria": searchCriteria},
					"dry_run":   true,
				}
				b, _ := json.MarshalIndent(preview, "", "  ")
				fmt.Fprintln(cmd.ErrOrStderr(), "(dry run -- no shopping session created)")
				fmt.Fprintln(cmd.OutOrStdout(), string(b))
				return nil
			}

			// Step 3: fire the mutation.
			startBody := map[string]any{"query": startAirShopMutation, "variables": map[string]any{"searchCriteria": searchCriteria}}
			startRaw, status, err := c.PostQueryWithParams(cmd.Context(), concurGraphQLPath, map[string]string{}, startBody)
			if err != nil {
				return classifyAPIError(err, flags)
			}
			if status == 401 || status == 403 {
				return fmt.Errorf("not authenticated (HTTP %d): run 'concur-pp-cli auth login --chrome' after logging in to concursolutions.com in Chrome", status)
			}
			if status < 200 || status >= 300 {
				return fmt.Errorf("concur GraphQL BFF returned HTTP %d", status)
			}
			var startEnv flightStartShopGQLEnvelope
			if err := json.Unmarshal(startRaw, &startEnv); err != nil {
				return fmt.Errorf("parsing startShop response: %w", err)
			}
			if len(startEnv.Errors) > 0 {
				return fmt.Errorf("concur GraphQL error starting flight shop: %s", startEnv.Errors[0].Detail())
			}
			shopID := startEnv.Data.Travel.Air.StartShop.ShopID
			if shopID == "" {
				return notFoundErr(fmt.Errorf("startShop did not return a shop id"))
			}

			// Step 4: poll until COMPLETE or timeout. Observed instant
			// completion in testing, but real-world shops may take longer.
			deadline := time.Now().Add(pollTimeout)
			var pollEnv flightPollShopGQLEnvelope
			for {
				pollBody := map[string]any{"query": pollAirShopQuery, "variables": map[string]any{"id": shopID, "pageSize": limit}}
				pollRaw, status, err := c.PostQueryWithParams(cmd.Context(), concurGraphQLPath, map[string]string{}, pollBody)
				if err != nil {
					return classifyAPIError(err, flags)
				}
				if status < 200 || status >= 300 {
					return fmt.Errorf("concur GraphQL BFF returned HTTP %d while polling", status)
				}
				if err := json.Unmarshal(pollRaw, &pollEnv); err != nil {
					return fmt.Errorf("parsing shop poll response: %w", err)
				}
				if len(pollEnv.Errors) > 0 {
					return fmt.Errorf("concur GraphQL error polling flight shop: %s", pollEnv.Errors[0].Detail())
				}
				if pollEnv.Data.Travel.Air.Shop.Status == "COMPLETE" {
					break
				}
				if time.Now().After(deadline) {
					return fmt.Errorf("flight search did not complete within %s (shop id %s, last status %s) -- results are perishable; this quote is not durable across retries", pollTimeout, shopID, pollEnv.Data.Travel.Air.Shop.Status)
				}
				time.Sleep(2 * time.Second)
			}

			content := pollEnv.Data.Travel.Air.Shop.SelectionSetV2.JourneyPage.Data.Content
			outputData, err := json.Marshal(content)
			if err != nil {
				return fmt.Errorf("marshaling journey results: %w", err)
			}
			prov := attachFreshness(DataProvenance{Source: "live"}, flags)

			if returnDate != "" && wantsHumanTable(cmd.OutOrStdout(), flags) {
				fmt.Fprintf(cmd.ErrOrStderr(), "note: showing outbound-leg flights only (%d of %d total across both legs); combined round-trip fares are a known gap -- see --help\n",
					len(content), pollEnv.Data.Travel.Air.Shop.SelectionSetV2.JourneyPage.Data.TotalElements)
			}
			if wantsHumanTable(cmd.OutOrStdout(), flags) {
				printProvenance(cmd, len(content), prov)
			}
			if flags.asJSON || (!isTerminal(cmd.OutOrStdout()) && !flags.csv && !flags.quiet && !flags.plain) {
				filtered := outputData
				if flags.selectFields != "" {
					filtered = filterFields(filtered, flags.selectFields)
				} else if flags.compact {
					filtered = compactFields(filtered)
				}
				wrapped, wrapErr := wrapWithProvenance(filtered, prov)
				if wrapErr != nil {
					return wrapErr
				}
				wrapped, wrapErr = wrapPlatformStructuredOutput(wrapped, flags, "results", true)
				if wrapErr != nil {
					return wrapErr
				}
				return printOutput(cmd.OutOrStdout(), wrapped, true)
			}
			if wantsHumanTable(cmd.OutOrStdout(), flags) {
				var items []map[string]any
				if json.Unmarshal(outputData, &items) == nil && len(items) > 0 {
					return printAutoTable(cmd.OutOrStdout(), items)
				}
			}
			return printOutputWithFlagsMeta(cmd.OutOrStdout(), outputData, flags, map[string]any{"source": "live"})
		},
	}
	cmd.Flags().StringVar(&fromQuery, "from", "", "Origin: city, airport name, or IATA code (required)")
	cmd.Flags().StringVar(&toQuery, "to", "", "Destination: city, airport name, or IATA code (required)")
	cmd.Flags().StringVar(&departDate, "depart", "", "Departure date, YYYY-MM-DD (required)")
	cmd.Flags().StringVar(&returnDate, "return", "", "Return date, YYYY-MM-DD (omit for one-way; see --help for the round-trip rendering gap)")
	cmd.Flags().StringVar(&cabin, "cabin", "", "ANY, ECONOMY, PREMIUM_ECONOMY, or BUSINESS_OR_FIRST (default: policy default)")
	cmd.Flags().IntVar(&limit, "limit", 10, "Maximum flights to return")
	cmd.Flags().DurationVar(&pollTimeout, "poll-timeout", 30*time.Second, "Maximum time to wait for shop results to settle")
	return cmd
}
