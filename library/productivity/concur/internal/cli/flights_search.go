// CONFIRMED 2026-08-17: mutation + polling flow constructed via live GraphQL
// introspection (Mutation -> TravelMutation.air -> TravelAirMutation.startShop,
// input TravelAirSearchRequestInput) and validated with a REAL shopping
// session against LAX->JFK/EWR/LGA for 2026-10-12 (125 real journeys
// returned, e.g. JetBlue LAX->JFK nonstop with 7 fare offers). This is a
// genuine write to the live Concur tenant -- creates a shopping session,
// books nothing, matches exactly what the UI's "Search Flights" button does.
// User-approved before this command was built.
//
// KNOWN GAP: journeyPage's flat result list is confirmed OUTBOUND-LEG-ONLY
// even for a 2-leg (round-trip) search request -- verified by fetching 50
// results and finding zero return-direction (destination airport -> origin
// airport) entries. Combined round-trip pricing likely requires a
// select-then-refine flow (journeyPage's "journeyIds" argument, or the
// unexplored selectedJourneys/recommendations fields) not yet mapped this
// session. This command therefore searches and renders ONE DIRECTION per
// call. --return is accepted and included in the search request (so a
// future version can add the second leg without a breaking change), but
// only the outbound leg's journeys are rendered -- this is stated in --help,
// not silently hidden. See .printing-press-patches/flights-hotels-search.json.
//
// Flight numbers are not rendered: TravelAirJourney's "segments" field
// (per-flight-number detail within a journey) was not introspected this
// session -- carrier name/code, times, duration, and nonstop/stop count are
// shown instead.
//
// This is a hand-authored file (no "Generated by ..." header) so
// `generate --force` preserves it.

package cli

