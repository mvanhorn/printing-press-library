// CONFIRMED 2026-08-17 via live GraphQL introspection (see trips_get.go's
// header comment for the introspection method -- full __schema is
// 403-blocked, single-type __type() lookups are not). locationSuggestions
// returns the TravelAirLocationSuggestion interface with 5 concrete types:
// TravelAirAirportLocation, TravelAirPlaceLocation (a metro/city grouping --
// this is how "NYC" resolves as a single entity spanning JFK/LGA/EWR),
// TravelAirCompanyLocation, TravelAirCompanyHubLocation, and
// TravelAirRailStationLocation. TravelAirPlaceLocation.children (a union of
// TravelAirAirportLocation | TravelAirRailStationLocation) is how a metro
// place expands into its individual airports -- e.g. querying "New York"
// returns one Place plus (via children) JFK/LGA/EWR as Airports.
//
// This is a hand-authored file (no "Generated by ..." header) so
// `generate --force` preserves it.

package cli

import (
	"encoding/json"
	"fmt"

	"github.com/spf13/cobra"
)

const flightLocationSuggestionsQuery = `query flightLocationSuggestions($query: String!) {
  travel {
    air {
      locationSuggestions(query: $query) {
        __typename
        id
        name
        address
        ... on TravelAirPlaceLocation {
          children {
            __typename
            ... on TravelAirAirportLocation {
              id
              name
              address
            }
            ... on TravelAirRailStationLocation {
              id
              name
              address
            }
          }
        }
      }
    }
  }
}`

type flightLocationsGQLEnvelope struct {
	Data struct {
		Travel struct {
			Air struct {
				LocationSuggestions []json.RawMessage `json:"locationSuggestions"`
			} `json:"air"`
		} `json:"travel"`
	} `json:"data"`
	Errors []gqlErrorEntry `json:"errors"`
}

func newFlightsLocationsCmd(flags *rootFlags) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "locations <query>",
		Short: "Resolve an airport, city, or metro name to Concur's travel location IDs",
		Long: `Resolve a free-text location query (city name, airport name, or IATA code)
to the location identifiers flights search needs. Metro areas like "New
York" resolve to a single TravelAirPlaceLocation whose "children" list
expands to the individual airports (e.g. JFK, LGA, EWR) -- pick a specific
airport id if you want one leg, or use the metro id if the search endpoint
accepts metro-level origins/destinations (unconfirmed until flights search
is built).`,
		Example:     "  concur-pp-cli flights locations LAX\n  concur-pp-cli flights locations \"New York\"",
		Annotations: map[string]string{"pp:endpoint": "flights.locations", "pp:method": "POST", "pp:path": "https://www-us2.api.concursolutions.com/cds/graphql", "mcp:read-only": "true"},
		Args:        cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			c, err := flags.newClient()
			if err != nil {
				return err
			}

			body := map[string]any{
				"query":     flightLocationSuggestionsQuery,
				"variables": map[string]any{"query": args[0]},
			}
			raw, status, err := c.PostQueryWithParams(cmd.Context(), concurGraphQLPath, map[string]string{}, body)
			if err != nil {
				return classifyAPIError(err, flags)
			}
			if status == 401 || status == 403 {
				return fmt.Errorf("not authenticated (HTTP %d): run 'concur-pp-cli auth login --chrome' after logging in to concursolutions.com in Chrome", status)
			}
			if status < 200 || status >= 300 {
				return fmt.Errorf("concur GraphQL BFF returned HTTP %d", status)
			}
			var env flightLocationsGQLEnvelope
			if err := json.Unmarshal(raw, &env); err != nil {
				return fmt.Errorf("parsing GraphQL response: %w", err)
			}
			if len(env.Errors) > 0 {
				return fmt.Errorf("concur GraphQL error: %s", env.Errors[0].Detail())
			}

			outputData, err := json.Marshal(env.Data.Travel.Air.LocationSuggestions)
			if err != nil {
				return fmt.Errorf("marshaling location suggestions: %w", err)
			}
			prov := attachFreshness(DataProvenance{Source: "live"}, flags)

			if wantsHumanTable(cmd.OutOrStdout(), flags) {
				printProvenance(cmd, len(env.Data.Travel.Air.LocationSuggestions), prov)
			}
			if flags.asJSON || (!isTerminal(cmd.OutOrStdout()) && !flags.csv && !flags.quiet && !flags.plain) {
				filtered := outputData
				if flags.selectFields != "" {
					filtered = filterFields(filtered, flags.selectFields)
				} else if flags.compact {
					filtered = compactFields(filtered)
				}
				wrapped, wrapErr := wrapWithProvenance(filtered, prov)
				if wrapErr != nil {
					return wrapErr
				}
				wrapped, wrapErr = wrapPlatformStructuredOutput(wrapped, flags, "results", true)
				if wrapErr != nil {
					return wrapErr
				}
				return printOutput(cmd.OutOrStdout(), wrapped, true)
			}
			if wantsHumanTable(cmd.OutOrStdout(), flags) {
				var items []map[string]any
				if json.Unmarshal(outputData, &items) == nil && len(items) > 0 {
					return printAutoTable(cmd.OutOrStdout(), items)
				}
			}
			return printOutputWithFlagsMeta(cmd.OutOrStdout(), outputData, flags, map[string]any{"source": "live"})
		},
	}
	return cmd
}
