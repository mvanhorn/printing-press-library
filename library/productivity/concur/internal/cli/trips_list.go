const concurGraphQLPath = "https://www-us2.api.concursolutions.com/cds/graphql"

// loadTripListQuery is captured verbatim from the Trips UI's real network
// traffic. Do not hand-edit the query body without re-verifying against a
// live capture -- Concur's BFF schema is internal and undocumented.
const loadTripListQuery = `query loadTripList($filter: TravelTripListFilterInput, $sort: TravelTripListSortInput, $nextToken: String) {
  travel {
    trips {
      importTripEnabled
      tripPlanEligible
      list(filter: $filter, sort: $sort, nextToken: $nextToken) {
        ... on TravelTripListSuccessResult {
          meta {
            nextToken
            __typename
          }
          trips {
            id
            recordLocator
            status
            displayStatus
            name
            bookings {
              type
              __typename
            }
            startDate
            endDate
            imageUrl
            approval {
              status
              __typename
            }
            __typename
          }
          __typename
        }
        ... on TravelErrorResponse {
          messages {
            code
            type
            __typename
          }
          __typename
        }
        __typename
      }
      __typename
    }
    __typename
  }
}`

// gqlErrorEntry models a GraphQL error entry. Concur's BFF wraps the
// genuinely useful message (e.g. "ID malformed") inside
// extensions.exception.data.error.errorMessage rather than the top-level
// message field, which is often just a generic "An error occurred" --
// Detail() prefers the nested message when present.
type gqlErrorEntry struct {
	Message    string `json:"message"`
	Extensions struct {
		Exception struct {
			Data struct {
				Error struct {
					ErrorMessage string `json:"errorMessage"`
					Reason       string `json:"reason"`
				} `json:"error"`
			} `json:"data"`
		} `json:"exception"`
	} `json:"extensions"`
}

// Detail returns the most specific message available for this error.
func (e gqlErrorEntry) Detail() string {
	if m := e.Extensions.Exception.Data.Error.ErrorMessage; m != "" {
		if r := e.Extensions.Exception.Data.Error.Reason; r != "" {
			return fmt.Sprintf("%s (%s)", m, r)
		}
		return m
	}
	return e.Message
}

// tripListGQLEnvelope models the loadTripList response. TravelTripListResult
// is a GraphQL union -- Meta/Trips are populated on
// TravelTripListSuccessResult, Messages on TravelErrorResponse. Both are
// optional pointers/slices so either shape unmarshals cleanly.
type tripListGQLEnvelope struct {
	Data struct {
		Travel struct {
			Trips struct {
				List struct {
					Typename string `json:"__typename"`
					Meta     *struct {
						NextToken *string `json:"nextToken"`
					} `json:"meta"`
					Trips    []json.RawMessage `json:"trips"`
					Messages []struct {
						Code string `json:"code"`
						Type string `json:"type"`
					} `json:"messages"`
				} `json:"list"`
			} `json:"trips"`
		} `json:"travel"`
	} `json:"data"`
	Errors []gqlErrorEntry `json:"errors"`
}

func newTripsListCmd(flags *rootFlags) *cobra.Command {
	var flagAll bool
	var flagPast bool
	var flagUpcoming bool

	cmd := &cobra.Command{
		Use:   "list",
		Short: "List the current user's upcoming and past trips (flights, hotels, car, rail)",
		Long: `List the current user's trips via the same GraphQL BFF the Concur Trips UI
itself uses (https://us2.concursolutions.com/travel/trip/list). Always scoped
to the current session's own user -- there is no cross-user lookup in this
operation (unlike the abandoned Trip v1.1/admin-role path).

Each trip's "bookings" field lists booking types present (Air, Hotel, Car,
Rail) but not full detail; use 'trips get <id>' for flight/hotel segment
detail.`,
		Example:     "  concur-pp-cli trips list\n  concur-pp-cli trips list --past --upcoming",
		Annotations: map[string]string{"pp:endpoint": "trips.list", "pp:method": "POST", "pp:path": "https://www-us2.api.concursolutions.com/cds/graphql", "mcp:read-only": "true"},
		RunE: func(cmd *cobra.Command, args []string) error {
			c, err := flags.newClient()
			if err != nil {
				return err
			}

			quick := []string{}
			// Default to both -- matches the UI's "All Filters" state, and
			// avoids the surprising default-hides-past-trips behavior the
			// live UI itself has on first load.
			if flagPast || (!flagPast && !flagUpcoming) {
				quick = append(quick, "PAST_TRIPS")
			}
			if flagUpcoming || (!flagPast && !flagUpcoming) {
				quick = append(quick, "UPCOMING_TRIPS")
			}

			var allTrips []json.RawMessage
			nextToken := ""
			for {
				variables := map[string]any{
					"filter": map[string]any{"quick": quick},
					"sort":   map[string]any{"sortBy": "START_DATE", "direction": "ASCENDING"},
				}
				if nextToken != "" {
					variables["nextToken"] = nextToken
				}
				body := map[string]any{"query": loadTripListQuery, "variables": variables}
				raw, status, err := c.PostQueryWithParams(cmd.Context(), concurGraphQLPath, map[string]string{}, body)
				if err != nil {
					return classifyAPIError(err, flags)
				}
				if status == 401 || status == 403 {
					return fmt.Errorf("not authenticated (HTTP %d): run 'concur-pp-cli auth login --chrome' after logging in to concursolutions.com in Chrome", status)
				}
				if status < 200 || status >= 300 {
					return fmt.Errorf("concur GraphQL BFF returned HTTP %d", status)
				}
				var env tripListGQLEnvelope
				if err := json.Unmarshal(raw, &env); err != nil {
					return fmt.Errorf("parsing GraphQL response: %w", err)
				}
				if len(env.Errors) > 0 {
					return fmt.Errorf("concur GraphQL error: %s", env.Errors[0].Detail())
				}
				list := env.Data.Travel.Trips.List
				if len(list.Messages) > 0 {
					return fmt.Errorf("concur trips.list error: %s (%s)", list.Messages[0].Type, list.Messages[0].Code)
				}
				allTrips = append(allTrips, list.Trips...)
				if !flagAll || list.Meta == nil || list.Meta.NextToken == nil || *list.Meta.NextToken == "" {
					break
				}
				nextToken = *list.Meta.NextToken
			}

			outputData, err := json.Marshal(allTrips)
			if err != nil {
				return fmt.Errorf("marshaling trip list: %w", err)
			}
			prov := attachFreshness(DataProvenance{Source: "live"}, flags)

			if wantsHumanTable(cmd.OutOrStdout(), flags) {
				printProvenance(cmd, len(allTrips), prov)
			}
			if flags.asJSON || (!isTerminal(cmd.OutOrStdout()) && !flags.csv && !flags.quiet && !flags.plain) {
				filtered := outputData
				if flags.selectFields != "" {
					filtered = filterFields(filtered, flags.selectFields)
				} else if flags.compact {
					filtered = compactFields(filtered)
				}
				wrapped, wrapErr := wrapWithProvenance(filtered, prov)
				if wrapErr != nil {
					return wrapErr
				}
				wrapped, wrapErr = wrapPlatformStructuredOutput(wrapped, flags, "results", true)
				if wrapErr != nil {
					return wrapErr
				}
				return printOutput(cmd.OutOrStdout(), wrapped, true)
			}
			if wantsHumanTable(cmd.OutOrStdout(), flags) {
				var items []map[string]any
				if json.Unmarshal(outputData, &items) == nil && len(items) > 0 {
					if err := printAutoTable(cmd.OutOrStdout(), items); err != nil {
						return err
					}
					if len(items) >= 25 {
						fmt.Fprintf(os.Stderr, "\nShowing %d results. To narrow: add --limit, --json --select, or filter flags.\n", len(items))
					}
					return nil
				}
			}
			return printOutputWithFlagsMeta(cmd.OutOrStdout(), outputData, flags, map[string]any{"source": "live"})
		},
	}
	cmd.Flags().BoolVar(&flagAll, "all", false, "Fetch all pages")
	cmd.Flags().BoolVar(&flagPast, "past", false, "Include past trips (default: both past and upcoming)")
	cmd.Flags().BoolVar(&flagUpcoming, "upcoming", false, "Include upcoming trips (default: both past and upcoming)")

	return cmd
}
