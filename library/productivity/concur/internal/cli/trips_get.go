// tripDetailQuery reaches TravelTripQuery.trip(id), which is the sibling
// detail operation to loadTripList's list(...) field (see trips_list.go).
// Field selection covers what the schema confirmed exists for flight (air)
// and hotel segments; car is included at __typename-only depth since its
// field set was not introspected in this session.
const tripDetailQuery = `query tripDetail($id: ID!) {
  travel {
    trips {
      trip(id: $id) {
        id
        name
        recordLocator
        status
        displayStatus
        localStartDate
        localEndDate
        bookings {
          id
          domain
          isCanceled
          air {
            confirmationNumber
            journeys {
              origin { iataCode name }
              destination { iataCode name }
              marketingCarrier { name iataCode }
              departureDateTime
              arrivalDateTime
              duration
              nonstop
              stopsCount
            }
          }
          hotel {
            bookingData {
              confirmationNumber
              checkInDate
              checkOutDate
              nightCount
              roomCount
              hotel { name }
            }
          }
          car {
            __typename
          }
        }
      }
    }
  }
}`

type tripDetailGQLEnvelope struct {
	Data struct {
		Travel struct {
			Trips struct {
				Trip json.RawMessage `json:"trip"`
			} `json:"trips"`
		} `json:"travel"`
	} `json:"data"`
	Errors []gqlErrorEntry `json:"errors"`
}

func newTripsGetCmd(flags *rootFlags) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "get <trip_id>",
		Short: "Get a trip's full itinerary detail, including flight, hotel, car, and rail booking segments",
		Long: `Get a trip's full itinerary via the same GraphQL BFF the Concur Trips UI
itself uses. <trip_id> is the "id" field from 'trips list' output, not a
record locator.`,
		Example:     "  concur-pp-cli trips get <id-from-trips-list>",
		Annotations: map[string]string{"pp:endpoint": "trips.get", "pp:method": "POST", "pp:path": "https://www-us2.api.concursolutions.com/cds/graphql", "mcp:read-only": "true"},
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 || args[0] == "" {
				if flags.asJSON {
					if printErr := printJSONFiltered(cmd.OutOrStdout(), map[string]any{
						"error": "missing required argument",
						"usage": fmt.Sprintf("%s%s", cmd.CommandPath(), " <trip_id>"),
					}, flags); printErr != nil {
						return printErr
					}
				}
				return usageErr(fmt.Errorf("missing required argument\nUsage: %s%s", cmd.CommandPath(), " <trip_id>"))
			}

			c, err := flags.newClient()
			if err != nil {
				return err
			}

			body := map[string]any{
				"query":     tripDetailQuery,
				"variables": map[string]any{"id": args[0]},
			}
			raw, status, err := c.PostQueryWithParams(cmd.Context(), concurGraphQLPath, map[string]string{}, body)
			if err != nil {
				return classifyAPIError(err, flags)
			}
			if status == 401 || status == 403 {
				return fmt.Errorf("not authenticated (HTTP %d): run 'concur-pp-cli auth login --chrome' after logging in to concursolutions.com in Chrome", status)
			}
			if status < 200 || status >= 300 {
				return fmt.Errorf("concur GraphQL BFF returned HTTP %d", status)
			}
			var env tripDetailGQLEnvelope
			if err := json.Unmarshal(raw, &env); err != nil {
				return fmt.Errorf("parsing GraphQL response: %w", err)
			}
			if len(env.Errors) > 0 {
				return fmt.Errorf("concur GraphQL error: %s", env.Errors[0].Detail())
			}
			if len(env.Data.Travel.Trips.Trip) == 0 || string(env.Data.Travel.Trips.Trip) == "null" {
				return notFoundErr(fmt.Errorf("no trip found with id %q", args[0]))
			}

			outputData := env.Data.Travel.Trips.Trip
			prov := attachFreshness(DataProvenance{Source: "live"}, flags)

			if wantsHumanTable(cmd.OutOrStdout(), flags) {
				printProvenance(cmd, 1, prov)
			}
			if flags.asJSON || (!isTerminal(cmd.OutOrStdout()) && !flags.csv && !flags.quiet && !flags.plain) {
				filtered := json.RawMessage(outputData)
				if flags.selectFields != "" {
					filtered = filterFields(filtered, flags.selectFields)
				} else if flags.compact {
					filtered = compactFields(filtered)
				}
				wrapped, wrapErr := wrapWithProvenance(filtered, prov)
				if wrapErr != nil {
					return wrapErr
				}
				wrapped, wrapErr = wrapPlatformStructuredOutput(wrapped, flags, "results", true)
				if wrapErr != nil {
					return wrapErr
				}
				return printOutput(cmd.OutOrStdout(), wrapped, true)
			}
			if wantsHumanTable(cmd.OutOrStdout(), flags) {
				var items []map[string]any
				if json.Unmarshal(outputData, &items) == nil && len(items) > 0 {
					if err := printAutoTable(cmd.OutOrStdout(), items); err != nil {
						return err
					}
					if len(items) >= 25 {
						fmt.Fprintf(os.Stderr, "\nShowing %d results. To narrow: add --limit, --json --select, or filter flags.\n", len(items))
					}
					return nil
				}
			}
			return printOutputWithFlagsMeta(cmd.OutOrStdout(), outputData, flags, map[string]any{"source": "live"})
		},
	}

	return cmd
}
