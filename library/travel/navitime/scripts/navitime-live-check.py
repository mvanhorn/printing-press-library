#!/usr/bin/env python3
"""Read-only built-binary acceptance with isolated caches and retained evidence.

Run --prepare-workflow before Printing Press shipcheck to refresh its future
Japan date and temporary home. A normal run needs --binary and --out-dir.
Uses only the Python standard library and the platform's /usr/bin/time.
"""
import argparse
import copy
import datetime as dt
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import time
from urllib.parse import parse_qs, urlparse
from zoneinfo import ZoneInfo

JAPAN = ZoneInfo("Asia/Tokyo")


def tomorrow():
    return (dt.datetime.now(JAPAN).date() + dt.timedelta(days=1)).isoformat()


def prepare_workflow(path, date):
    home = tempfile.mkdtemp(prefix="navitime-workflow-")
    cache = str(Path(home) / "public-cache")
    Path(path).write_text(f'''# Generated by scripts/navitime-live-check.py --prepare-workflow.
# Refresh before verification: uses the next Japan date and a private temp home.
# Read-only public requests; the route response stores all snapshot detail.
workflows:
  - name: resolve-dated-route-and-inspect-snapshot
    primary: true
    steps:
      - command: places search Tokyo --type station --limit 5 --home {home} --cache-dir {cache}
        mode: live
        expect_fields: [meta, places, ambiguous]
        extract:
          from_ref: places[0].ref
      - command: places search Kyoto --type station --limit 5 --home {home} --cache-dir {cache}
        mode: live
        expect_fields: [meta, places, ambiguous]
        extract:
          to_ref: places[0].ref
      - command: routes search --from ${{from_ref}} --to ${{to_ref}} --depart-at {date}T09:00 --limit 1 --home {home} --cache-dir {cache}
        mode: live
        expect_fields: [meta, query, routes, returned_alternatives]
        extract:
          route_id: routes[0].id
      - command: routes show ${{route_id}} --home {home} --cache-dir {cache}
        mode: local
        expect_fields: [meta, route, stored_snapshot, notes]
''')
    return {"workflow": str(Path(path).resolve()), "japan_date": date, "isolated_home": home, "isolated_cache": cache}


def timestamp(value):
    return dt.datetime.fromisoformat(value)


class Acceptance:
    def __init__(self, binary, out_dir, date, max_requests, resume=False, min_interval=1.0, recovery_attempts=0, cooldown=30, recovery_delay=15):
        self.binary = str(Path(binary).resolve())
        self.out = Path(out_dir).resolve()
        self.out.mkdir(parents=True, exist_ok=True)
        self.cache = self.out / "cache"
        self.home = self.out / "home"
        self.date = date
        self.max_requests = max_requests
        self.total_requests = 0
        self.cases = []
        self.failed = None
        self.system = platform.system()
        self.min_interval = min_interval
        self.recovery_attempts = recovery_attempts
        self.cooldown = cooldown
        self.recovery_delay = recovery_delay
        self.last_run = 0.0
        self.reused = {}
        self.failed_attempts = []
        self.previous_report = None
        self.attempt_numbers = {}
        if resume:
            report_path = self.out / "report.json"
            previous = json.loads(report_path.read_text())
            if previous["japan_date"] != date or previous["binary"] != self.binary:
                raise RuntimeError("resume requires the same Japan date and built binary path")
            suffix = 1
            archive = self.out / ("report.attempt-" + str(suffix) + ".json")
            while archive.exists():
                suffix += 1
                archive = self.out / ("report.attempt-" + str(suffix) + ".json")
            shutil.copyfile(report_path, archive)
            self.previous_report = str(archive)
            self.previous_state = previous
            self.failed_attempts = copy.deepcopy(previous.get("failed_attempts", []))
            for row in previous["cases"]:
                passed = row["assertions"] and all(a["passed"] for a in row["assertions"])
                if passed:
                    self.reused[row["case"]] = row
                else:
                    self.failed_attempts.append(row)
            recorded = list(self.reused.values()) + self.failed_attempts
            self.total_requests = sum(r["request_count"] for r in recorded if isinstance(r.get("request_count"), int))
            for row in recorded:
                name = row["case"]
                self.attempt_numbers[name] = self.attempt_numbers.get(name, 0) + 1
        if self.system not in ("Darwin", "Linux"):
            raise RuntimeError("RSS measurement supports macOS and Linux")
        if not Path(self.binary).is_file():
            raise RuntimeError("--binary must name an already built CLI")

    def run(self, name, args, expected_exit=0, cache=None):
        if name in self.reused:
            row = copy.deepcopy(self.reused[name])
            row["assertions"] = []
            row["evidence_reused"] = True
            self.cases.append(row)
            value = None if expected_exit else json.loads(Path(row["stdout_file"]).read_bytes())
            self.check(row["exit_code"] == expected_exit, "immutable passed binary evidence reused without another invocation", row)
            return value, row
        prior = [row for row in self.failed_attempts if row["case"] == name]
        prior_failure = bool(prior)
        if prior_failure:
            attempts = max(0, 1 + self.recovery_attempts - self.attempt_numbers.get(name, 0))
            if attempts == 0:
                row = copy.deepcopy(prior[-1])
                row["evidence_reused"] = True
                self.cases.append(row)
                raise AssertionError(name + ": source challenge recovery budget exhausted; no further request")
            time.sleep(self.cooldown)
        else:
            attempts = 1 + self.recovery_attempts
        for attempt in range(attempts):
            delay = self.min_interval - (time.monotonic() - self.last_run)
            if delay > 0:
                time.sleep(delay)
            try:
                return self._run_once(name, args, expected_exit, cache)
            except AssertionError:
                row = self.cases[-1]
                diagnostic = Path(row["stderr_file"]).read_text()
                challenged = row["exit_code"] == 5 and re.search(r"HTTP (202|403)\b", diagnostic)
                if not challenged or attempt + 1 >= attempts:
                    raise
                row["source_failure"] = "temporary source challenge; never interpreted as no data"
                self.failed_attempts.append(row)
                self.cases.pop()
                time.sleep(self.recovery_delay)
        raise RuntimeError("recovery loop did not return a result")

    def _run_once(self, name, args, expected_exit=0, cache=None):
        attempt = self.attempt_numbers.get(name, 0) + 1
        self.attempt_numbers[name] = attempt
        stem = name if attempt == 1 else name + ".attempt-" + str(attempt)
        out_path = self.out / (stem + ".json")
        err_path = self.out / (stem + ".stderr")
        rss_path = self.out / (stem + ".time")
        command = [self.binary, *args, "--cache-dir", str(cache or self.cache), "--home", str(self.home), "--timeout", "25s", "--metrics"]
        if self.system == "Darwin":
            measured = ["/usr/bin/time", "-l", "-o", str(rss_path), *command]
        else:
            measured = ["/usr/bin/time", "-f", '{"peak_rss_kib":%M,"wall_seconds":%e}', "-o", str(rss_path), *command]
        env = os.environ.copy()
        # Prevent a surrounding verify harness from short-circuiting live reads.
        env.pop("PRINTING_PRESS_VERIFY", None)
        env.pop("PRINTING_PRESS_DOGFOOD", None)
        started = time.perf_counter()
        completed = subprocess.run(measured, stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env, timeout=35)
        wall_ms = (time.perf_counter() - started) * 1000
        self.last_run = time.monotonic()
        out_path.write_bytes(completed.stdout)
        err_path.write_bytes(completed.stderr)
        raw_time = rss_path.read_text()
        if self.system == "Darwin":
            match = re.search(r"^\s*(\d+)\s+maximum resident set size", raw_time, re.M)
            peak_rss_bytes = int(match.group(1)) if match else 0
            source_unit = "bytes"
        else:
            measured_stats = json.loads(raw_time.splitlines()[-1])
            peak_rss_bytes = measured_stats["peak_rss_kib"] * 1024
            source_unit = "KiB"
        metric_lines = [line for line in completed.stderr.decode().splitlines() if line.startswith("{")]
        metrics = json.loads(metric_lines[-1]) if metric_lines else {}
        row = {
            "case": name, "command": command[1:], "exit_code": completed.returncode,
            "stdout_file": str(out_path), "stderr_file": str(err_path), "rss_file": str(rss_path),
            "output_bytes": len(completed.stdout), "request_count": metrics.get("request_count"),
            "cache_hits": metrics.get("cache_hits"), "latency_ms": metrics.get("latency_ms"),
            "wall_ms": round(wall_ms, 3), "peak_rss_bytes": peak_rss_bytes,
            "rss_source_unit": source_unit, "metrics": metrics, "assertions": [],
        }
        self.cases.append(row)
        requests = metrics.get("request_count")
        if isinstance(requests, int):
            self.total_requests += requests
        self.check(isinstance(requests, int) and 0 <= requests <= 2, "bounded actual request count per command", row)
        self.check(self.total_requests <= self.max_requests, "bounded total actual requests including failed attempts", row)
        self.check(completed.returncode == expected_exit, f"exit {expected_exit}", row)
        self.check(peak_rss_bytes > 0, "platform-correct peak RSS recorded", row)
        self.check(len(metric_lines) == 1, "one separate metric JSON value on stderr", row)
        self.check(metrics.get("output_bytes") == len(completed.stdout), "metric output bytes equal actual binary stdout", row)
        if expected_exit:
            self.check(not completed.stdout, "typed error leaves stdout empty", row)
            return None, row
        self.check(len(completed.stdout.splitlines()) == 1, "default compact one JSON value", row)
        value = json.loads(completed.stdout)
        self.check(isinstance(value, dict), "domain object envelope", row)
        self.check(len(completed.stderr.decode().splitlines()) == 1, "metrics only on successful stderr", row)
        return value, row

    def check(self, condition, assertion, row):
        row["assertions"].append({"assertion": assertion, "passed": bool(condition)})
        if not condition:
            raise AssertionError(f'{row["case"]}: {assertion}')

    def source(self, value, row, hit=False, mode=None):
        meta = value["meta"]
        self.check(meta["source_url"].startswith("https://japantravel.navitime.com/"), "canonical public source URL", row)
        self.check(meta["fetched_at"] is not None and meta["source_updated_at"] is None, "fetched date and unknown source update preserved", row)
        self.check(meta["cache_hit"] is hit, "expected cache provenance", row)
        self.check(row["request_count"] == 0 if hit else 1 <= row["request_count"] <= 2, "cached and uncached requests measured separately", row)
        if hit:
            self.check(row["cache_hits"] >= 1, "cache hit recorded", row)
        if mode:
            params = parse_qs(urlparse(meta["source_url"]).query)
            self.check(params.get("search_time_mode") == [mode], "source URL carries requested time mode", row)

    def route(self, value, row, max_count=3):
        routes = value["routes"]
        self.check(0 < len(routes) <= max_count, "bounded nonempty source alternatives", row)
        for route in routes:
            self.check(route["id"] and route["source_id"] is None, "local snapshot ID and honest missing source ID", row)
            self.check(route["source_url"] == value["meta"]["source_url"], "summary source URL preserved", row)
            self.check(route["fare"]["currency"] == "JPY" and route["fare"]["pass_holder_cost_jpy"] is None, "fare units and unknown pass-holder cost", row)
            departure, arrival = timestamp(route["departure_at"]), timestamp(route["arrival_at"])
            self.check(departure.utcoffset() == dt.timedelta(hours=9) and arrival >= departure, "JST dates and forward arrival", row)
            self.check("legs" not in route and "fare_groups" not in route, "summary omits stored full detail", row)
        return routes

    def query(self, mode, value, goal="station:00001756", extra=()):
        return ["routes", "search", "--from", "station:00006668", "--to", goal, "--" + mode, value, *extra]

    def matrix(self):
        date = self.date
        jp_args = ["places", "search", "大久保", "--type", "station", "--limit", "5"]
        jp, row = self.run("lookup-japanese-uncached", jp_args)
        self.source(jp, row)
        self.check(jp["ambiguous"] and 1 < len(jp["places"]) <= 5, "Japanese ambiguity remains bounded candidates", row)
        self.check(len({p["id"] for p in jp["places"]}) == len(jp["places"]), "distinct source station IDs", row)
        cached, row = self.run("lookup-japanese-cached", jp_args)
        self.source(cached, row, hit=True)
        self.check(cached["places"] == jp["places"], "cached public candidates unchanged", row)
        en, row = self.run("lookup-english", ["places", "search", "Tokyo", "--type", "station", "--limit", "5"])
        self.source(en, row)
        self.check(any(p["ref"] == "station:00006668" for p in en["places"]), "English lookup includes Tokyo source station", row)
        poi, row = self.run("lookup-poi", ["places", "search", "東京スカイツリー", "--type", "spot", "--limit", "5"])
        self.source(poi, row)
        self.check(poi["places"] and all(p["kind"] == "spot" for p in poi["places"]), "spot-only lookup preserves POI kind", row)
        skytree = next((p for p in poi["places"] if "スカイツリー" in json.dumps(p["name"], ensure_ascii=False) or "skytree" in json.dumps(p["name"]).lower()), None)
        self.check(skytree is not None and skytree["ref"].startswith("spot:"), "source Skytree reference found", row)
        depart_args = self.query("depart-at", date + "T09:00")
        depart, row = self.run("route-depart-uncached", depart_args)
        self.source(depart, row, mode="start-time")
        routes = self.route(depart, row)
        self.check(all(timestamp(r["departure_at"]) >= timestamp(date + "T09:00:00+09:00") for r in routes), "departures honor explicit lower bound", row)
        cached, row = self.run("route-depart-cached", depart_args)
        self.source(cached, row, hit=True, mode="start-time")
        self.check(cached["routes"] == routes, "cached summaries retain IDs and values", row)
        detail, row = self.run("route-stored-detail", ["routes", "show", routes[0]["id"]])
        self.check(row["request_count"] == 0 and detail["route"]["id"] == routes[0]["id"], "snapshot matches summary without HTTP", row)
        self.check(detail["stored_snapshot"] and detail["meta"]["fetched_at"] == depart["meta"]["fetched_at"], "stored detail retains original freshness", row)
        legs, groups = detail["route"]["legs"], detail["route"]["fare_groups"]
        self.check(legs and groups, "ordered legs and full fare groups present", row)
        self.check(any(g["base_fare_jpy"] is not None for g in groups), "source base fare represented", row)
        self.check(any(leg["seat_options"] for leg in legs), "optional source seat supplements represented", row)
        self.check(len({g["id"] for g in groups}) == len(groups), "fare groups are distinct rather than added per leg", row)
        for leg in legs:
            if leg["departure_at"] and leg["arrival_at"]:
                self.check(timestamp(leg["arrival_at"]) >= timestamp(leg["departure_at"]), "each leg's dates move forward", row)
        projected, row = self.run("route-projected-cached", [*depart_args, "--agent", "--fields", "routes.id,routes.fare.total_jpy"])
        self.check(row["request_count"] == 0 and list(projected) == ["routes"], "projection stays native with no additional request", row)
        self.check(projected["routes"][0]["id"] == routes[0]["id"] and projected["routes"][0]["fare"]["total_jpy"] == routes[0]["fare"]["total_jpy"], "dotted projection preserves actual values", row)
        self.check(row["output_bytes"] < len(json.dumps(depart, separators=(",", ":")).encode()), "projected output is smaller than summary", row)
        arrive, row = self.run("route-arrive", self.query("arrive-by", date + "T12:00"))
        self.source(arrive, row, mode="goal-time")
        self.check(all(timestamp(r["arrival_at"]) <= timestamp(date + "T12:00:00+09:00") for r in self.route(arrive, row)), "arrivals honor explicit deadline", row)
        first, row = self.run("route-first", self.query("first-on", date))
        self.source(first, row, mode="first-operation")
        first_routes = self.route(first, row)
        self.check(timestamp(first_routes[0]["departure_at"]).date().isoformat() == date and timestamp(first_routes[0]["departure_at"]).hour < 12, "first service uses requested Japan date", row)
        last, row = self.run("route-last", self.query("last-on", date))
        self.source(last, row, mode="last-operation")
        last_routes = self.route(last, row)
        self.check(timestamp(last_routes[0]["departure_at"]) > timestamp(first_routes[0]["departure_at"]), "last service is later than first service", row)
        night, row = self.run("route-overnight", self.query("depart-at", date + "T23:58", goal="station:00004254"))
        self.source(night, row, mode="start-time")
        night_routes = self.route(night, row)
        self.check(any(timestamp(r["arrival_at"]).date() > dt.date.fromisoformat(date) for r in night_routes), "overnight route crosses Japan midnight with full dates", row)
        night_detail, row = self.run("route-overnight-detail", ["routes", "show", night_routes[0]["id"]])
        self.check(row["request_count"] == 0, "overnight detail needs zero HTTP", row)
        for leg in night_detail["route"]["legs"]:
            if leg["departure_at"] and leg["arrival_at"]:
                self.check(timestamp(leg["arrival_at"]) >= timestamp(leg["departure_at"]), "overnight leg rollover is forward", row)
        spot_route, row = self.run("route-poi", self.query("depart-at", date + "T09:00", goal=skytree["ref"]))
        self.source(spot_route, row, mode="start-time")
        spot_routes = self.route(spot_route, row)
        self.check(parse_qs(urlparse(spot_route["meta"]["source_url"]).query).get("goalCode") == [skytree["id"]], "POI route uses exact source goalCode", row)
        spot_detail, row = self.run("route-poi-detail", ["routes", "show", spot_routes[0]["id"]])
        self.check(row["request_count"] == 0 and any(l["kind"] == "walking" for l in spot_detail["route"]["legs"]), "POI detail preserves walking legs without HTTP", row)
        pass_route, row = self.run("route-pass", self.query("depart-at", date + "T09:00", extra=("--pass", "japan_rail_pass")))
        self.source(pass_route, row, mode="start-time")
        pass_routes = self.route(pass_route, row)
        self.check(parse_qs(urlparse(pass_route["meta"]["source_url"]).query).get("pass_list") == ["japan_rail_pass"], "one requested pass appears in effective source query", row)
        self.check(pass_routes[0]["pass"]["requested_id"] == "japan_rail_pass" and pass_routes[0]["fare"]["pass_holder_cost_jpy"] is None, "pass provenance does not invent zero cost", row)
        pass_detail, row = self.run("route-pass-detail", ["routes", "show", pass_routes[0]["id"]])
        service = json.dumps(pass_detail["route"]["legs"]).lower()
        self.check(row["request_count"] == 0 and ("hikari" in service or "kodama" in service), "representative JR Pass route retains observed service choice", row)
        catalogue, row = self.run("passes-cached-catalogue", ["passes", "list", "--limit", "10"])
        self.source(catalogue, row, hit=True)
        self.check(catalogue["total"] >= 10 and len(catalogue["passes"]) == 10, "catalogue uses bounded local page", row)
        self.check(any(p["id"] == "japan_rail_pass" and p["live_tested"] for p in catalogue["passes"]), "catalogue distinguishes representative live-tested pass", row)
        empty, row = self.run("passes-empty-page", ["passes", "list", "--offset", str(catalogue["total"])])
        self.check(row["request_count"] == 0 and empty["passes"] == [] and empty["notes"], "local empty catalogue page returns [] and note", row)
        zero_args = ["routes", "compare", *depart_args[2:], "--sort", "fare", "--max-fare", "0"]
        zero, row = self.run("compare-zero-results", zero_args)
        self.check(row["request_count"] == 0 and zero["routes"] == [] and zero["notes"], "local caps return honest zero results without unrelated routes", row)
        compared, row = self.run("compare-cached", ["routes", "compare", *depart_args[2:], "--sort", "fare"])
        self.check(row["request_count"] == 0 and 0 < len(compared["routes"]) <= 3, "comparison ranks cached alternatives only", row)
        fares = [r["fare"]["total_jpy"] for r in compared["routes"]]
        known = [f for f in fares if f is not None]
        self.check(known == sorted(known) and fares[:len(known)] == known, "known fares rank ascending before unknowns", row)
        refreshed, row = self.run("passes-refreshed-catalogue", ["passes", "list", "--refresh", "--limit", "10"])
        self.source(refreshed, row)
        self.check(refreshed["total"] == catalogue["total"] and len(refreshed["passes"]) == 10, "catalogue refresh makes one bounded public read", row)
        no_cache, row = self.run("lookup-no-cache", [*jp_args, "--no-cache"])
        self.source(no_cache, row)
        self.check(row["metrics"]["cache_writes"] == 0, "no-cache bypasses cache writes", row)
        raw_route, row = self.run("route-no-cache", [*depart_args, "--no-cache", "--limit", "1"])
        self.source(raw_route, row, mode="start-time")
        self.check(row["metrics"]["cache_writes"] == 0 and len(raw_route["routes"]) == 1, "no-cache route remains bounded without persistence", row)
        self.run("detail-not-found", ["routes", "show", "not-a-stored-route"], expected_exit=3)
        latest, row = self.run("detail-empty-latest", ["routes", "show", "--latest"], cache=self.out / "empty-cache")
        self.check(row["request_count"] == 0 and latest["route"] is None and latest["notes"], "empty latest is honest null with note and zero HTTP", row)
        capabilities, row = self.run("capabilities-static", ["capabilities"])
        self.check(row["request_count"] == 0, "static capability provenance makes no request", row)
        statuses = {c["status"] for c in capabilities["capabilities"]}
        self.check({"verified", "advertised", "credential_gated", "unavailable"} <= statuses, "all source capability statuses represented", row)

    def local_tail(self):
        if not hasattr(self, "previous_state"):
            raise RuntimeError("--local-tail-only requires --resume")
        previous = self.previous_state
        # Preserve the source-blocked route case and its outcome. Completing
        # unrelated local checks must not convert that failure into a pass.
        self.cases = copy.deepcopy(previous["cases"])
        self.failed_attempts = copy.deepcopy(previous.get("failed_attempts", []))
        self.failed = previous.get("failure")
        _, row = self.run("detail-not-found", ["routes", "show", "not-a-stored-route"], expected_exit=3)
        self.check(row["request_count"] == 0, "not-found snapshot requires zero HTTP", row)
        latest, row = self.run("detail-empty-latest", ["routes", "show", "--latest"], cache=self.out / "empty-cache")
        self.check(row["request_count"] == 0 and latest["route"] is None and latest["notes"], "empty latest is honest null with note and zero HTTP", row)
        capabilities, row = self.run("capabilities-static", ["capabilities"])
        self.check(row["request_count"] == 0, "static capability provenance makes no request", row)
        statuses = {c["status"] for c in capabilities["capabilities"]}
        self.check({"verified", "advertised", "credential_gated", "unavailable"} <= statuses, "all source capability statuses represented", row)

    def report(self):
        value = {
            "status": "failed" if self.failed else "passed", "failure": self.failed,
            "japan_date": self.date, "binary": self.binary, "platform": self.system,
            "requests": self.total_requests, "max_requests": self.max_requests,
            "case_count": len(self.cases), "assertion_count": sum(len(c["assertions"]) for c in self.cases),
            "cases": self.cases, "failed_attempts": self.failed_attempts,
            "previous_report_file": self.previous_report,
            "evidence_reused_case_count": sum(c.get("evidence_reused", False) for c in self.cases),
        }
        path = self.out / "report.json"
        path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n")
        return path, value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary")
    parser.add_argument("--out-dir")
    parser.add_argument("--date", default=tomorrow(), help="explicit next-day Japan date; default computed in Asia/Tokyo")
    parser.add_argument("--max-requests", type=int, default=26, help="bounded matrix; at most two attempts per public read")
    parser.add_argument("--resume", action="store_true", help="reuse immutable passed evidence; execute failed/missing cases only")
    parser.add_argument("--local-tail-only", action="store_true", help="complete zero-HTTP tail while retaining any prior source failure")
    parser.add_argument("--min-interval", type=float, default=1.0, help="minimum seconds between new binary invocations, outside measured latency")
    parser.add_argument("--recovery-attempts", type=int, choices=(0, 1, 2), default=0, help="at most two read-only recovery attempts for HTTP202/403 challenges")
    parser.add_argument("--cooldown", type=float, default=30, help="seconds before retrying a previously challenged case")
    parser.add_argument("--recovery-delay", type=float, default=15, help="seconds between bounded challenge recovery attempts")
    parser.add_argument("--prepare-workflow", action="store_true")
    parser.add_argument("--workflow-file", default=str(Path(__file__).resolve().parent.parent / "workflow_verify.yaml"))
    args = parser.parse_args()
    dt.date.fromisoformat(args.date)
    if args.prepare_workflow:
        print(json.dumps(prepare_workflow(args.workflow_file, args.date)))
        return 0
    if not args.binary or not args.out_dir:
        parser.error("--binary and --out-dir are required for live acceptance")
    if min(args.min_interval, args.cooldown, args.recovery_delay) < 0:
        parser.error("pacing and cooldown durations must be zero or greater")
    acceptance = Acceptance(args.binary, args.out_dir, args.date, args.max_requests, args.resume, args.min_interval, args.recovery_attempts, args.cooldown, args.recovery_delay)
    try:
        if args.local_tail_only:
            acceptance.local_tail()
        else:
            acceptance.matrix()
    except (AssertionError, KeyError, ValueError, TypeError, StopIteration, subprocess.TimeoutExpired) as error:
        acceptance.failed = str(error) or type(error).__name__
    path, report = acceptance.report()
    print(json.dumps({"status": report["status"], "report": str(path), "requests": report["requests"], "assertions": report["assertion_count"], "failure": report["failure"]}, ensure_ascii=False))
    return 1 if acceptance.failed else 0


