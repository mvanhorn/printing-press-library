func TestMealFeedbackMechanismFor(t *testing.T) {
	tests := []struct {
		category         string
		wantMechanism    string
		wantForkableType string
		wantOK           bool
	}{
		{"missing-item", "reported-issue", "member_reported_missing_meals", true},
		{"missing-side", "reported-issue", "member_reported_missing_sides", true},
		{"wrong-item", "contact-form", "Report Issue", true},
		{"quality", "contact-form", "Report Issue", true},
		{"late", "contact-form", "Delivery Status", true},
		{"other", "contact-form", "General Inquiry", true},
		{"", "", "", false},
		{"spicy", "", "", false},
		{"MISSING-ITEM", "", "", false}, // case handled by the caller (lowercased before this check), not the mapper itself
	}
	for _, tt := range tests {
		gotMechanism, gotType, gotOK := mealFeedbackMechanismFor(tt.category)
		if gotOK != tt.wantOK || (gotOK && (gotMechanism != tt.wantMechanism || gotType != tt.wantForkableType)) {
			t.Errorf("mealFeedbackMechanismFor(%q) = (%q, %q, %v), want (%q, %q, %v)",
				tt.category, gotMechanism, gotType, gotOK, tt.wantMechanism, tt.wantForkableType, tt.wantOK)
		}
	}
}

func TestComposeMealFeedbackMessage(t *testing.T) {
	tests := []struct {
		name              string
		deliveryID        int64
		note, venue, item string
		pieceID           string
		wantContains      []string
		wantNotContains   []string
	}{
		{
			name:            "note only",
			deliveryID:      12345,
			note:            "Rice was missing",
			wantContains:    []string{"Rice was missing", "Delivery ID: 12345"},
			wantNotContains: []string{"venue:", "item:", "piece:"},
		},
		{
			name:         "full context",
			deliveryID:   12345,
			note:         "Rice was missing",
			venue:        "Example Venue",
			item:         "Example Item",
			pieceID:      "abc-123",
			wantContains: []string{"Rice was missing", "Delivery ID: 12345", "venue: Example Venue", "item: Example Item", "piece: abc-123"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := composeMealFeedbackMessage(tt.deliveryID, tt.note, tt.venue, tt.item, tt.pieceID)
			for _, want := range tt.wantContains {
				if !strings.Contains(got, want) {
					t.Errorf("composeMealFeedbackMessage(...) = %q, want substring %q", got, want)
				}
			}
			for _, notWant := range tt.wantNotContains {
				if strings.Contains(got, notWant) {
					t.Errorf("composeMealFeedbackMessage(...) = %q, want NOT to contain %q", got, notWant)
				}
			}
		})
	}
}

// TestAppendAndReadMealFeedback exercises the local ledger append/read
// round-trip against a temp data dir (via FORKABLE_DATA_DIR) so it never
// touches the caller's real ledger.
func TestAppendAndReadMealFeedback(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("FORKABLE_DATA_DIR", dir)

	entries, err := readMealFeedback()
	if err != nil {
		t.Fatalf("readMealFeedback() on empty store = %v, want nil error", err)
	}
	if len(entries) != 0 {
		t.Fatalf("readMealFeedback() on empty store = %d entries, want 0", len(entries))
	}

	first := MealFeedbackEntry{DeliveryID: 11111, Category: "missing-item", Mechanism: "reported-issue", ForkableType: "member_reported_missing_meals", Note: "no rice", Submitted: true, IssueID: "issue-1"}
	second := MealFeedbackEntry{DeliveryID: 22222, Category: "quality", Mechanism: "contact-form", ForkableType: "Report Issue", Note: "cold food", Submitted: false}
	if err := appendMealFeedback(first); err != nil {
		t.Fatalf("appendMealFeedback(first) = %v, want nil", err)
	}
	if err := appendMealFeedback(second); err != nil {
		t.Fatalf("appendMealFeedback(second) = %v, want nil", err)
	}

	entries, err = readMealFeedback()
	if err != nil {
		t.Fatalf("readMealFeedback() after writes = %v, want nil error", err)
	}
	if len(entries) != 2 {
		t.Fatalf("readMealFeedback() after writes = %d entries, want 2", len(entries))
	}
	if entries[0].DeliveryID != first.DeliveryID || !entries[0].Submitted || entries[0].Mechanism != "reported-issue" {
		t.Errorf("entries[0] = %+v, want delivery %d / submitted=true / mechanism=reported-issue", entries[0], first.DeliveryID)
	}
	if entries[1].DeliveryID != second.DeliveryID || entries[1].Submitted || entries[1].Mechanism != "contact-form" {
		t.Errorf("entries[1] = %+v, want delivery %d / submitted=false / mechanism=contact-form", entries[1], second.DeliveryID)
	}
}

// TestTruncateValidUTF8 guards the same truncation contract feedback.go
// established for CLI-feedback text, applied here to the meal-issue note --
// plus the UTF-8-boundary case a plain byte-index slice gets wrong (a
// multibyte rune straddling the cut point must be dropped whole, not left
// as a partial/invalid tail that round-trips through JSON as U+FFFD).
func TestTruncateValidUTF8(t *testing.T) {
	t.Run("under limit is untouched", func(t *testing.T) {
		s := "short note"
		if got := truncateValidUTF8(s, mealFeedbackMaxNoteLen); got != s {
			t.Errorf("truncateValidUTF8(%q, %d) = %q, want unchanged", s, mealFeedbackMaxNoteLen, got)
		}
	})

	t.Run("ASCII over limit truncates to exact length", func(t *testing.T) {
		longNote := strings.Repeat("x", mealFeedbackMaxNoteLen+500)
		got := truncateValidUTF8(longNote, mealFeedbackMaxNoteLen)
		if len(got) != mealFeedbackMaxNoteLen {
			t.Fatalf("len(truncateValidUTF8(...)) = %d, want %d", len(got), mealFeedbackMaxNoteLen)
		}
		if !utf8.ValidString(got) {
			t.Fatalf("truncateValidUTF8(...) = %q, want valid UTF-8", got)
		}
	})

	t.Run("multibyte rune straddling the cut point is dropped whole", func(t *testing.T) {
		// "café" ends in a 2-byte rune (é). Cut at len("caf")+1 = 4 bytes,
		// landing exactly inside that rune's second byte -- a bare
		// s[:4] would keep the first byte of "é" as an invalid trailing byte.
		s := "café"
		cut := len("caf") + 1
		got := truncateValidUTF8(s, cut)
		if !utf8.ValidString(got) {
			t.Fatalf("truncateValidUTF8(%q, %d) = %q, want valid UTF-8", s, cut, got)
		}
		if got != "caf" {
			t.Errorf("truncateValidUTF8(%q, %d) = %q, want %q (the straddling rune dropped whole)", s, cut, got, "caf")
		}
	})
}
