// contactFormPath mirrors internal/client's contactFormPath constant (see
// that file's comment for why the cli and client packages each keep their
// own copy of this literal -- forkableGraphQLPath/graphqlPath already do
// the same for the GraphQL route).
const contactFormPath = "/submit_contact_form"

// mealFeedbackCategories are the accepted --category values. missing-item
// and missing-side route to the real addMemberReportedIssue mutation; the
// rest route to the contact form (see mealFeedbackMechanismFor). Categories
// unrelated to a delivered-meal problem (Change Admin, Account Settings,
// Billing & Payment, Suggest an Improvement, Request Meal Adjustment) are
// intentionally not exposed here -- out of scope for this command.
var mealFeedbackCategories = []string{"missing-item", "missing-side", "wrong-item", "quality", "late", "other"}

// mealFeedbackMechanismFor maps a --category to the mechanism that files it
// and the value that mechanism expects:
//
//   - "reported-issue": forkableType is the addMemberReportedIssue `type`
//     enum value (module 372 in mc/js/*.js: "member_reported_missing_meals",
//     "member_reported_missing_sides" -- the third enum value,
//     "member_reported_other_issues", is deliberately not exposed here
//     because the SPA's own copy for it says to use Forkable Support
//     instead, i.e. the contact form below).
//   - "contact-form": forkableType is the contact-form `subject` string
//     (module 29822: base ["Missing Meal","Change Admin"], extended
//     ["Delivery Status","Request Meal Adjustment","Account Settings",
//     "Billing & Payment","Report Issue","Suggest an Improvement",
//     "General Inquiry"]).
//
// Returns ok=false for anything not in mealFeedbackCategories.
func mealFeedbackMechanismFor(category string) (mechanism, forkableType string, ok bool) {
	switch category {
	case "missing-item":
		return "reported-issue", "member_reported_missing_meals", true
	case "missing-side":
		return "reported-issue", "member_reported_missing_sides", true
	case "wrong-item", "quality":
		return "contact-form", "Report Issue", true
	case "late":
		return "contact-form", "Delivery Status", true
	case "other":
		return "contact-form", "General Inquiry", true
	default:
		return "", "", false
	}
}

const mealFeedbackMaxNoteLen = 4096

// truncateValidUTF8 byte-truncates s to at most maxLen bytes, then strips
// any trailing partial rune left by that byte-index slice -- a plain
// s[:maxLen] can cut a multibyte UTF-8 character in half, which then
// round-trips through JSON as a lossy U+FFFD in both the support request
// and the local ledger.
func truncateValidUTF8(s string, maxLen int) string {
	if len(s) <= maxLen {
		return s
	}
	return strings.ToValidUTF8(s[:maxLen], "")
}

// MealFeedbackEntry is one line in the local delivery-issue ledger -- a
// record of what this CLI attempted/sent to Forkable, kept independent of
// the real report/ticket so the member has their own copy.
type MealFeedbackEntry struct {
	DeliveryID    int64     `json:"delivery_id"`
	OrderID       int64     `json:"order_id,omitempty"`
	Category      string    `json:"category"`
	Mechanism     string    `json:"mechanism"` // "reported-issue" or "contact-form"
	ForkableType  string    `json:"forkable_type"`
	Note          string    `json:"note"`
	Venue         string    `json:"venue,omitempty"`
	Item          string    `json:"item,omitempty"`
	PieceID       string    `json:"piece_id,omitempty"`
	RequestRefund bool      `json:"request_refund,omitempty"`
	RequestCredit bool      `json:"request_credit,omitempty"`
	IssueID       string    `json:"issue_id,omitempty"`   // set for reported-issue on success
	Resolution    string    `json:"resolution,omitempty"` // set for reported-issue on success
	Submitted     bool      `json:"submitted"`
	CLI           string    `json:"cli"`
	Version       string    `json:"version"`
	Timestamp     time.Time `json:"timestamp"`
}

func mealFeedbackFilePath() (string, error) {
	dir, err := cliutil.DataDir()
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", fmt.Errorf("creating meal-feedback data dir: %w", err)
	}
	return filepath.Join(dir, "meal-feedback.jsonl"), nil
}

func appendMealFeedback(entry MealFeedbackEntry) error {
	p, err := mealFeedbackFilePath()
	if err != nil {
		return err
	}
	f, err := os.OpenFile(p, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o600)
	if err != nil {
		return fmt.Errorf("opening meal-feedback ledger: %w", err)
	}
	defer f.Close()
	return json.NewEncoder(f).Encode(entry)
}

func readMealFeedback() ([]MealFeedbackEntry, error) {
	p, err := mealFeedbackFilePath()
	if err != nil {
		return nil, err
	}
	data, err := os.ReadFile(p)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var entries []MealFeedbackEntry
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		var e MealFeedbackEntry
		if err := json.Unmarshal([]byte(line), &e); err != nil {
			continue
		}
		entries = append(entries, e)
	}
	return entries, nil
}

// composeMealFeedbackMessage builds the contact-form message body. Forkable's
// form has no structured delivery/venue/item/piece field, so this folds that
// context into the free-text message the way a human filling out the same
// form by hand would. Only used by the contact-form mechanism --
// addMemberReportedIssue takes orderId/pieceId as real fields instead.
func composeMealFeedbackMessage(deliveryID int64, note, venue, item, pieceID string) string {
	var b strings.Builder
	b.WriteString(note)
	b.WriteString(fmt.Sprintf("\n\n(Sent via forkable-pp-cli meal feedback. Delivery ID: %d", deliveryID))
	if venue != "" {
		b.WriteString(fmt.Sprintf(", venue: %s", venue))
	}
	if item != "" {
		b.WriteString(fmt.Sprintf(", item: %s", item))
	}
	if pieceID != "" {
		b.WriteString(fmt.Sprintf(", piece: %s", pieceID))
	}
	b.WriteString(".)")
	return b.String()
}

// meCore is the minimal `me` projection the contact-form mechanism needs --
// name and email. Deliberately narrower than promoted_account.go's full
// current-user query.
type meCore struct {
	FullName string `json:"fullName"`
	Email    string `json:"email"`
}

const meCoreQuery = `query { me { fullName email } }`

func fetchMeCore(ctx context.Context, flags *rootFlags) (meCore, error) {
	data, err := fetchGraphQL(ctx, flags, meCoreQuery)
	if err != nil {
		return meCore{}, err
	}
	var wrap struct {
		Me meCore `json:"me"`
	}
	if err := json.Unmarshal(data, &wrap); err != nil {
		return meCore{}, fmt.Errorf("parsing account info: %w", err)
	}
	return wrap.Me, nil
}

// deliveryLookupRow is the shared shape for the two best-effort
// myDeliveries lookups below (market id for the contact form, order id for
// a given piece). Both use the same "from: <today>" query pattern -- see
// resolveDeliveryMarketID's comment for why a wide/historical `from` does
// not work empirically.
type deliveryLookupRow struct {
	ID                      int64      `json:"id"`
	ReportMissingItemCutoff *time.Time `json:"reportMissingItemCutoff"`
	Club                    struct {
		Market struct {
			ID int64 `json:"id"`
		} `json:"market"`
	} `json:"club"`
	Orders []struct {
		ID     int64 `json:"id"`
		Pieces []struct {
			ID string `json:"id"`
		} `json:"pieces"`
	} `json:"orders"`
}

func fetchTodayDeliveryLookup(ctx context.Context, flags *rootFlags) ([]deliveryLookupRow, error) {
	today := time.Now().UTC().Format("2006-01-02")
	query := fmt.Sprintf(`query { myDeliveries (from: "%s") { id reportMissingItemCutoff club { market { id } } orders { id pieces { id } } } }`, today)
	data, err := fetchGraphQL(ctx, flags, query)
	if err != nil {
		return nil, err
	}
	var wrap struct {
		MyDeliveries []deliveryLookupRow `json:"myDeliveries"`
	}
	if err := json.Unmarshal(data, &wrap); err != nil {
		return nil, err
	}
	return wrap.MyDeliveries, nil
}

// checkReportMissingItemCutoff returns a clear, actionable error if
// deliveryID's cutoff for addMemberReportedIssue (type
// member_reported_missing_meals/sides) has already passed. Forkable
// enforces this server-side -- confirmed live: a same-day submission after
// the cutoff is rejected with a payload-level error ("This user flow is
// only available until <time>. Please refresh page to rate meal."), not a
// GraphQL schema error, so this check exists to fail fast with a clearer
// message instead of spending a live mutation call on a doomed request.
// A nil cutoff (delivery not found, or Forkable simply didn't set one --
// e.g. the next day's not-yet-delivered order) is not treated as blocking;
// only a definite past cutoff blocks.
func checkReportMissingItemCutoff(ctx context.Context, flags *rootFlags, deliveryID int64) error {
	rows, err := fetchTodayDeliveryLookup(ctx, flags)
	if err != nil {
		return nil // best-effort; let the real mutation surface any real problem
	}
	for _, d := range rows {
		if d.ID != deliveryID {
			continue
		}
		if d.ReportMissingItemCutoff != nil && time.Now().UTC().After(*d.ReportMissingItemCutoff) {
			return fmt.Errorf("Forkable's report-missing-item window for delivery %d closed at %s (local restaurant time) -- use --category other instead to reach Forkable support directly", deliveryID, d.ReportMissingItemCutoff.Local().Format(time.Kitchen))
		}
		return nil
	}
	return nil
}

// resolveDeliveryMarketID looks up the market id for deliveryID, matching
// the market_id field the my-account SPA sends alongside a contact-form
// submission. Best-effort: an error or a not-found delivery returns 0 so
// the caller can still submit with market_id omitted rather than fail the
// whole command over a field Forkable's own form only opportunistically
// fills in (see the SPA's `1===this.marketOptions.length?...:...` fallback).
func resolveDeliveryMarketID(ctx context.Context, flags *rootFlags, deliveryID int64) int64 {
	rows, err := fetchTodayDeliveryLookup(ctx, flags)
	if err != nil {
		return 0
	}
	for _, d := range rows {
		if d.ID == deliveryID {
			return d.Club.Market.ID
		}
	}
	return 0
}

// resolveOrderIDForPiece finds which order within deliveryID contains
// pieceID, so the caller only has to supply --piece (already needed to
// identify which meal) rather than also requiring a separate --order flag.
// Returns 0 if not found -- the caller must then require an explicit
// orderId some other way, since addMemberReportedIssue has no default.
func resolveOrderIDForPiece(ctx context.Context, flags *rootFlags, deliveryID int64, pieceID string) int64 {
	rows, err := fetchTodayDeliveryLookup(ctx, flags)
	if err != nil {
		return 0
	}
	for _, d := range rows {
		if d.ID != deliveryID {
			continue
		}
		for _, o := range d.Orders {
			for _, p := range o.Pieces {
				if p.ID == pieceID {
					return o.ID
				}
			}
		}
	}
	return 0
}

// submitContactForm POSTs to Forkable's my-account "Contact Support" REST
// endpoint -- see the file header for why this is not a GraphQL mutation.
func submitContactForm(ctx context.Context, flags *rootFlags, body map[string]any) error {
	c, err := flags.newClient()
	if err != nil {
		return err
	}
	_, status, err := c.Post(ctx, contactFormPath, body)
	if err != nil {
		return classifyAPIError(err, flags)
	}
	if status == 401 || status == 403 {
		return fmt.Errorf("not authenticated (HTTP %d): run 'forkable-pp-cli auth login --chrome' after logging in to forkable.com in Chrome", status)
	}
	if status < 200 || status >= 300 {
		return fmt.Errorf("forkable contact-form submission returned HTTP %d", status)
	}
	return nil
}

// reportedIssue mirrors the fields myReportedIssues / addMemberReportedIssue
// return that this CLI surfaces. Confirmed live against the real schema:
// AddMemberReportedIssueInput.orderId is Int, .pieceId is String, .type is
// a required String! (see meal_feedback.go's mutation constant below for
// the exact enum values).
type reportedIssue struct {
	ID                    string `json:"id"`
	Type                  string `json:"type"`
	Notes                 string `json:"notes"`
	Resolution            string `json:"resolution"`
	RequestRefund         bool   `json:"requestRefund"`
	RequestGiftCard       bool   `json:"requestGiftCard"`
	RequestReOrder        bool   `json:"requestReOrder"`
	ReplacementOnfleetURL string `json:"replacementOnfleetUrl"`
}

const reportedIssueReturning = `errors issue { id type notes resolution requestRefund requestGiftCard requestReOrder replacementOnfleetUrl }`

// submitMemberReportedIssue wraps addMemberReportedIssue -- the real
// GraphQL mutation backing the per-meal "Report Missing Item" widget.
// Confirmed live via schema-validation probes (missing/invalid input
// arguments): input type is AddMemberReportedIssueInput!.
func submitMemberReportedIssue(ctx context.Context, flags *rootFlags, input map[string]any) (reportedIssue, error) {
	op := buildMutation("addMemberReportedIssue", "AddMemberReportedIssue", reportedIssueReturning)
	data, err := mutateGraphQL(ctx, flags, op, map[string]any{"input": input})
	if err != nil {
		return reportedIssue{}, err
	}
	var wrap struct {
		AddMemberReportedIssue struct {
			Issue reportedIssue `json:"issue"`
		} `json:"addMemberReportedIssue"`
	}
	if err := json.Unmarshal(data, &wrap); err != nil {
		return reportedIssue{}, fmt.Errorf("parsing addMemberReportedIssue response: %w", err)
	}
	return wrap.AddMemberReportedIssue.Issue, nil
}

// newMealFeedbackCmd wraps the two mechanisms described in the file header.
// It is added as a subcommand of the existing `meal` parent in
// forkable_orders.go, alongside the GraphQL-backed set/set-all/confirm/skip.
func newMealFeedbackCmd(flags *rootFlags) *cobra.Command {
	var category, note, venue, item, pieceID string
	var requestRefund, requestCredit, confirm bool
	cmd := &cobra.Command{
		Use:   "feedback <deliveryId>",
		Short: "Report a problem with a delivered meal to Forkable (missing item/side via a real report, everything else via support)",
		Long: strings.Trim(`
Reports a problem with a delivered meal using whichever real Forkable
mechanism actually handles it -- there are two, and --category picks:

  missing-item / missing-side -> addMemberReportedIssue, a real GraphQL
    mutation backing the my-account app's per-meal "Report Missing Item"
    widget. Delivery/order/piece-scoped, ties into the courier's delivery
    photos, and supports refund/credit resolution tracking via
    --request-refund/--request-credit. Requires --piece (the order id is
    resolved automatically by looking up which order contains that piece).

  wrong-item / quality / late / other -> POST /submit_contact_form, the
    plain REST call behind the generic "Contact Support" modal (subjects:
    Report Issue / Report Issue / Delivery Status / General Inquiry).
    Forkable's own UI sends "other issues" here too. No dedicated field for
    delivery/venue/item/piece, so those are folded into the message text.

Both were discovered by static analysis of the my-account SPA bundle, not
from any public API doc. Dry-run by default like every other 'meal' write
command: prints the exact request and stops. Pass --confirm to actually
submit it. Every --confirm attempt (submitted or rejected by Forkable) is
also recorded in the local meal-feedback.jsonl ledger -- preview-only runs
are not. Building either request touches the network even during preview --
addMemberReportedIssue needs the order id resolved from --piece, and the
contact form needs your name/email and the delivery's market id.`, "\n"),
		Example: strings.Trim(`
  forkable-pp-cli meal feedback 12345 --category missing-item --note "Missing rice, that was pictured" --piece <uuid> --confirm
  forkable-pp-cli meal feedback 12345 --category missing-item --piece <uuid> --request-refund --confirm
  forkable-pp-cli meal feedback 12345 --category quality --note "Cold on arrival" --item "Example Item" --venue "Example Venue" --confirm`, "\n"),
		Args: cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 && cmd.Flags().NFlag() == 0 {
				return cmd.Help()
			}
			if dryRunOK(flags) {
				emitDryRunShortCircuit(cmd, flags, "report a problem with a delivered meal to Forkable")
				return nil
			}
			if len(args) < 1 {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("delivery id is required"))
			}
			deliveryID, err := parseInt64(args[0])
			if err != nil {
				return usageErr(fmt.Errorf("invalid delivery id %q: %w", args[0], err))
			}
			category = strings.ToLower(strings.TrimSpace(category))
			if category == "" {
				category = "other"
			}
			mechanism, forkableType, ok := mealFeedbackMechanismFor(category)
			if !ok {
				return usageErr(fmt.Errorf("invalid --category %q: expected one of %s", category, strings.Join(mealFeedbackCategories, ", ")))
			}
			note = truncateValidUTF8(strings.TrimSpace(note), mealFeedbackMaxNoteLen)
			if mechanism == "contact-form" && note == "" {
				return usageErr(fmt.Errorf("--note is required for --category %q", category))
			}
			if (requestRefund || requestCredit) && mechanism != "reported-issue" {
				return usageErr(fmt.Errorf("--request-refund/--request-credit only apply to --category missing-item or missing-side"))
			}

			ctx, cancel := boundCtx(cmd.Context(), flags)
			defer cancel()

			entry := MealFeedbackEntry{
				DeliveryID:    deliveryID,
				Category:      category,
				Mechanism:     mechanism,
				ForkableType:  forkableType,
				Note:          note,
				Venue:         strings.TrimSpace(venue),
				Item:          strings.TrimSpace(item),
				PieceID:       strings.TrimSpace(pieceID),
				RequestRefund: requestRefund,
				RequestCredit: requestCredit,
				CLI:           "forkable-pp-cli",
				Version:       version,
				Timestamp:     time.Now().UTC(),
			}

			if mechanism == "reported-issue" {
				pieceID = strings.TrimSpace(pieceID)
				if pieceID == "" {
					return usageErr(fmt.Errorf("--piece is required for --category %q (get it from 'deliveries list' or 'served-history')", category))
				}
				orderID := resolveOrderIDForPiece(ctx, flags, deliveryID, pieceID)
				if orderID == 0 {
					return fmt.Errorf("could not find an order containing piece %q under delivery %d (myDeliveries only returns a rolling recent/upcoming window -- this delivery may have aged out of it)", pieceID, deliveryID)
				}
				entry.OrderID = orderID
				if err := checkReportMissingItemCutoff(ctx, flags, deliveryID); err != nil {
					return err
				}

				input := map[string]any{
					"type":    forkableType,
					"orderId": orderID,
					"pieceId": pieceID,
					"notes":   note,
				}
				if requestRefund {
					input["requestRefund"] = true
				}
				if requestCredit {
					input["requestGiftCard"] = true
				}
				action := fmt.Sprintf("report %q for piece %s (order %d, delivery %d)", forkableType, pieceID, orderID, deliveryID)
				op := buildMutation("addMemberReportedIssue", "AddMemberReportedIssue", reportedIssueReturning)
				if !confirmOrPreview(cmd, flags, confirm, action, op, map[string]any{"input": input}) {
					return nil
				}

				issue, submitErr := submitMemberReportedIssue(ctx, flags, input)
				entry.Submitted = submitErr == nil
				if submitErr == nil {
					entry.IssueID = issue.ID
					entry.Resolution = issue.Resolution
				}
				_ = appendMealFeedback(entry) // best-effort local record; submission result below is authoritative
				if submitErr != nil {
					return submitErr
				}
				return emitMealFeedbackSuccess(cmd, flags, entry, issue)
			}

			// contact-form mechanism
			who, err := fetchMeCore(ctx, flags)
			if err != nil {
				return fmt.Errorf("looking up account info for the support request: %w", err)
			}
			marketID := resolveDeliveryMarketID(ctx, flags, deliveryID)

			message := composeMealFeedbackMessage(deliveryID, note, venue, item, pieceID)
			body := map[string]any{
				"name":    who.FullName,
				"email":   who.Email,
				"subject": forkableType,
				"message": message,
			}
			if marketID != 0 {
				body["market_id"] = marketID
			}

			action := fmt.Sprintf("submit a %q support request to Forkable for delivery %d", forkableType, deliveryID)
			if !confirmOrPreview(cmd, flags, confirm, action, "POST "+contactFormPath, body) {
				return nil
			}

			submitErr := submitContactForm(ctx, flags, body)
			entry.Submitted = submitErr == nil
			_ = appendMealFeedback(entry) // best-effort local record; submission result below is authoritative
			if submitErr != nil {
				return submitErr
			}
			return emitMealFeedbackSuccess(cmd, flags, entry, reportedIssue{})
		},
	}
	cmd.Flags().StringVar(&category, "category", "other", "issue category: "+strings.Join(mealFeedbackCategories, ", "))
	cmd.Flags().StringVar(&note, "note", "", "free-text description of the issue (required for wrong-item/quality/late/other; optional detail for missing-item/missing-side)")
	cmd.Flags().StringVar(&venue, "venue", "", "venue name for reference (contact-form categories only; not sent for missing-item/missing-side)")
	cmd.Flags().StringVar(&item, "item", "", "menu item name for reference (contact-form categories only)")
	cmd.Flags().StringVar(&pieceID, "piece", "", "piece UUID from 'deliveries list'/'served-history' -- required for missing-item/missing-side, optional reference otherwise")
	cmd.Flags().BoolVar(&requestRefund, "request-refund", false, "ask for a refund (missing-item/missing-side only)")
	cmd.Flags().BoolVar(&requestCredit, "request-credit", false, "ask for a gift-card credit instead of a refund (missing-item/missing-side only)")
	cmd.Flags().BoolVar(&confirm, "confirm", false, "actually submit the request (default: preview only)")

	cmd.AddCommand(newMealFeedbackListCmd(flags))
	return cmd
}

// emitMealFeedbackSuccess prints the outcome of either mechanism. issue is
// the zero value for the contact-form mechanism (it returns no structured
// payload to show).
func emitMealFeedbackSuccess(cmd *cobra.Command, flags *rootFlags, entry MealFeedbackEntry, issue reportedIssue) error {
	machineOut := flags.asJSON || flags.agent || !isTerminal(cmd.OutOrStdout())
	if machineOut {
		out := map[string]any{"submitted": true, "entry": entry}
		if entry.Mechanism == "reported-issue" {
			out["issue"] = issue
		}
		return printJSONFiltered(cmd.OutOrStdout(), out, flags)
	}
	if entry.Mechanism == "reported-issue" {
		fmt.Fprintf(cmd.OutOrStdout(), "reported %q for delivery %d (issue id: %s)\n", entry.ForkableType, entry.DeliveryID, issue.ID)
		return nil
	}
	fmt.Fprintf(cmd.OutOrStdout(), "submitted to Forkable support: %q for delivery %d\n", entry.ForkableType, entry.DeliveryID)
	return nil
}

