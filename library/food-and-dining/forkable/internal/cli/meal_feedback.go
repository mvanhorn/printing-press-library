// Meal/delivery issue reporting. Two real Forkable mechanisms exist,
// neither of which is documented and both discovered by static analysis of
// the my-account SPA bundle (mc/js/app.*.js, mc/js/372.*.js):
//
//   - addMemberReportedIssue -- a REAL GraphQL mutation (same wire shape as
//     replacePiece/confirmDelivery/etc. in forkable_orders.go) backing the
//     per-meal "Report Missing Item" widget (MealReportIssue component,
//     module 372). It is delivery/order/piece-scoped, ties into the
//     courier's Onfleet delivery photos, and supports refund/gift-card/
//     re-order resolution tracking via myReportedIssues. This is the
//     product-correct path for a missing meal or missing side.
//   - POST /submit_contact_form -- a plain REST call (NOT GraphQL) backing
//     the generic "Contact Support" modal. The SPA's own copy for "Other
//     Issues" says outright: "please use Forkable Support" -- i.e.
//     Forkable's own UI only routes non-missing-item problems here.
//
// --category picks the mechanism: missing-item/missing-side go through
// addMemberReportedIssue; wrong-item/quality/late/other go through the
// contact form. Every --confirm attempt (submitted or rejected by
// Forkable) is also recorded in a local meal-feedback.jsonl ledger -- a
// preview-only run (no --confirm) makes no live-writing attempt, so it is
// not logged. Like every other meal-management write in
// this file, submission is DRY-RUN BY DEFAULT and gated behind --confirm.
//
// This is a hand-authored file (no "Generated by ..." header) so
// `generate --force` preserves it, matching forkable_orders.go.

