// parseModifierSelections turns repeated `--modifier <modifierId>:<optId>[,<optId>...]`
// flag values into the `selectionsHash` object the replacePiece mutation expects:
// an object keyed by modifier ID (as a string) whose value is the array of chosen
// option IDs — matching the SPA's `selections[modifierId] = [optionIds]` shape.
// Menu items with a required modifier (e.g. "Choose Protein", min:1) are rejected
// by the API without this, which is why a bare item/menu set fails on them.
func parseModifierSelections(specs []string) (map[string][]int64, error) {
	if len(specs) == 0 {
		return nil, nil
	}
	out := make(map[string][]int64, len(specs))
	for _, spec := range specs {
		spec = strings.TrimSpace(spec)
		if spec == "" {
			continue
		}
		modPart, optPart, ok := strings.Cut(spec, ":")
		if !ok {
			return nil, fmt.Errorf("invalid --modifier %q: expected <modifierId>:<optionId>[,<optionId>...]", spec)
		}
		modID, err := parseInt64(modPart)
		if err != nil {
			return nil, fmt.Errorf("invalid modifier id in %q: %w", spec, err)
		}
		opts, err := parseIDList(optPart)
		if err != nil {
			return nil, fmt.Errorf("invalid option id in %q: %w", spec, err)
		}
		if len(opts) == 0 {
			return nil, fmt.Errorf("invalid --modifier %q: no option ids given", spec)
		}
		key := strconv.FormatInt(modID, 10)
		out[key] = append(out[key], opts...)
	}
	return out, nil
}

// newMealSetCmd wraps replacePiece: override the auto-picked meal for a day.
func newMealSetCmd(flags *rootFlags) *cobra.Command {
	var itemID, menuID, oldPieceID, note string
	var modifiers []string
	var confirm bool
	cmd := &cobra.Command{
		Use:   "set <deliveryId>",
		Short: "Set a specific meal item for one delivery day (replacePiece).",
		Long: strings.Trim(`
Override the meal Forkable auto-selected for a delivery day with a specific
item. --item and --menu are required; find them with 'menus' and 'meal-scores'.
--replace-piece is the id of the currently-selected piece to replace (from
'deliveries' or 'served-history'); omit it to add a new piece.

Items with required options (e.g. "Choose Protein") need --modifier, repeatable:
--modifier <modifierId>:<optionId>[,<optionId>...]. Find modifier and option ids
under each item's "modifiers" in 'menus'. Without a required modifier the API
rejects the order (e.g. "You must select an option for Choose Protein").

Dry-run by default: prints the mutation and variables unless --confirm is set.`, "\n"),
		Example: "  forkable-pp-cli meal set 12345 --item 678 --menu 90 --modifier 16:10 --replace-piece <uuid> --confirm",
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 && cmd.Flags().NFlag() == 0 {
				return cmd.Help()
			}
			if dryRunOK(flags) {
				emitDryRunShortCircuit(cmd, flags, "set a meal for a delivery day")
				return nil
			}
			if len(args) < 1 {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("delivery id is required"))
			}
			deliveryID, err := parseInt64(args[0])
			if err != nil {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("invalid delivery id %q: %w", args[0], err))
			}
			if itemID == "" || menuID == "" {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("--item and --menu are required"))
			}
			itemN, err := parseInt64(itemID)
			if err != nil {
				return usageErr(fmt.Errorf("invalid --item %q: %w", itemID, err))
			}
			menuN, err := parseInt64(menuID)
			if err != nil {
				return usageErr(fmt.Errorf("invalid --menu %q: %w", menuID, err))
			}
			selections, err := parseModifierSelections(modifiers)
			if err != nil {
				return usageErr(err)
			}
			input := map[string]any{
				"deliveryId": deliveryID,
				"menuId":     menuN,
				"itemId":     itemN,
				"myMeals":    true,
			}
			if oldPieceID != "" {
				// Forkable piece IDs are UUID strings, not integers.
				input["oldPieceId"] = oldPieceID
			}
			if len(selections) > 0 {
				input["selectionsHash"] = selections
			}
			if note != "" {
				input["instructions"] = note
			}
			op := buildMutation("replacePiece", "ReplacePiece", "delivery { id } errors")
			action := fmt.Sprintf("set item %d (menu %d) on delivery %d", itemN, menuN, deliveryID)
			if !confirmOrPreview(cmd, flags, confirm, action, op, map[string]any{"input": input}) {
				return nil
			}
			ctx, cancel := boundCtx(cmd.Context(), flags)
			defer cancel()
			data, err := mutateGraphQL(ctx, flags, op, map[string]any{"input": input})
			if err != nil {
				return err
			}
			return emitMutationResult(cmd, flags, data)
		},
	}
	cmd.Flags().StringVar(&itemID, "item", "", "menu item id to select (required)")
	cmd.Flags().StringVar(&menuID, "menu", "", "menu id the item belongs to (required)")
	cmd.Flags().StringVar(&oldPieceID, "replace-piece", "", "id of the currently-selected piece to replace")
	cmd.Flags().StringArrayVar(&modifiers, "modifier", nil, "modifier selection <modifierId>:<optionId>[,<optionId>...] (repeatable; required for items with a mandatory option like Choose Protein)")
	cmd.Flags().StringVar(&note, "note", "", "special instructions for the kitchen")
	cmd.Flags().BoolVar(&confirm, "confirm", false, "actually apply the change (default: preview only)")
	return cmd
}

