func newNovelReorderCmd(flags *rootFlags) *cobra.Command {
	var ontoDelivery, replacePieceID string
	var confirm bool
	cmd := &cobra.Command{
		Use:   "reorder <fromDate>",
		Short: "Repeat the meal you had on a past date onto an upcoming delivery day.",
		Long: strings.Trim(`
Look up the meal served to you on <fromDate> (YYYY-MM-DD) and apply that same
item to an upcoming delivery given by --onto <deliveryId>. Forkable auto-selects
meals and has no native reorder, so this reads your served history and reuses
the item via the same override the web app performs.

Dry-run by default: prints the mutation and variables unless --confirm is set.`, "\n"),
		Example: "  forkable-pp-cli reorder 2026-06-15 --onto 12345 --confirm",
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 && cmd.Flags().NFlag() == 0 {
				return cmd.Help()
			}
			if dryRunOK(flags) {
				emitDryRunShortCircuit(cmd, flags, "repeat a past meal onto an upcoming delivery")
				return nil
			}
			if len(args) < 1 {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("a from-date (YYYY-MM-DD) is required"))
			}
			fromDate := strings.TrimSpace(args[0])
			if ontoDelivery == "" {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("--onto <deliveryId> is required"))
			}
			ontoID, err := parseInt64(ontoDelivery)
			if err != nil {
				return usageErr(fmt.Errorf("invalid --onto %q: %w", ontoDelivery, err))
			}
			// Read served history to find the item served on fromDate.
			menuID, itemID, name, err := lookupServedItem(cmd, flags, fromDate)
			if err != nil {
				return err
			}
			input := map[string]any{
				"deliveryId": ontoID,
				"menuId":     menuID,
				"itemId":     itemID,
				"myMeals":    true,
			}
			if replacePieceID != "" {
				// Forkable piece IDs are UUID strings, not integers.
				input["oldPieceId"] = replacePieceID
			}
			op := buildMutation("replacePiece", "ReplacePiece", "delivery { id } errors")
			action := fmt.Sprintf("reorder %q (item %d, menu %d) onto delivery %d", name, itemID, menuID, ontoID)
			if !confirmOrPreview(cmd, flags, confirm, action, op, map[string]any{"input": input}) {
				return nil
			}
			ctx, cancel := boundCtx(cmd.Context(), flags)
			defer cancel()
			data, err := mutateGraphQL(ctx, flags, op, map[string]any{"input": input})
			if err != nil {
				return err
			}
			return emitMutationResult(cmd, flags, data)
		},
	}
	cmd.Flags().StringVar(&ontoDelivery, "onto", "", "upcoming delivery id to apply the meal to (required)")
	cmd.Flags().StringVar(&replacePieceID, "replace-piece", "", "id of the currently-selected piece on the target delivery to replace")
	cmd.Flags().BoolVar(&confirm, "confirm", false, "actually apply the change (default: preview only)")
	return cmd
}

// lookupServedItem finds the menuId + itemId of the meal served on a given
// date by reading served history. The served-history query does not return
// menuId/itemId on pieces, so this uses a targeted deliveries query that does.
func lookupServedItem(cmd *cobra.Command, flags *rootFlags, date string) (menuID, itemID int64, name string, err error) {
	const q = `query { myDeliveries (from: "2000-01-01") { forDeliveryAt orders { forDeliveryAt menu { id } pieces { id name menuId itemId } } } }`
	ctx, cancel := boundCtx(cmd.Context(), flags)
	defer cancel()
	data, err := fetchGraphQL(ctx, flags, q)
	if err != nil {
		return 0, 0, "", err
	}
	var wrap struct {
		MyDeliveries []struct {
			ForDeliveryAt string `json:"forDeliveryAt"`
			Orders        []struct {
				ForDeliveryAt string `json:"forDeliveryAt"`
				Menu          struct {
					ID int64 `json:"id"`
				} `json:"menu"`
				Pieces []struct {
					ID     int64  `json:"id"`
					Name   string `json:"name"`
					MenuID int64  `json:"menuId"`
					ItemID int64  `json:"itemId"`
				} `json:"pieces"`
			} `json:"orders"`
		} `json:"myDeliveries"`
	}
	if err := json.Unmarshal(data, &wrap); err != nil {
		return 0, 0, "", fmt.Errorf("parsing deliveries: %w", err)
	}
	dateOnly := func(s string) string {
		if len(s) >= 10 {
			return s[:10]
		}
		return s
	}
	for _, d := range wrap.MyDeliveries {
		for _, o := range d.Orders {
			when := o.ForDeliveryAt
			if when == "" {
				when = d.ForDeliveryAt
			}
			if dateOnly(when) != date {
				continue
			}
			for _, p := range o.Pieces {
				if p.ItemID != 0 {
					mID := p.MenuID
					if mID == 0 {
						mID = o.Menu.ID
					}
					return mID, p.ItemID, p.Name, nil
				}
			}
		}
	}
	return 0, 0, "", fmt.Errorf("no served meal found for %s (check the date with 'served-history')", date)
}
