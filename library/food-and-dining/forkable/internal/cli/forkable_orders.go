// Meal-management write surface for Forkable. Forkable auto-selects meals;
// there is no placeOrder/createOrder mutation. A member's real ordering
// controls are the GraphQL mutations the my-account SPA sends:
//
//	replacePiece       — override the auto-picked meal for one delivery day
//	replaceAllPieces   — apply one item across several delivery days
//	confirmDelivery    — confirm (or unconfirm) a day's delivery
//	removeDelivery(-ies) — skip/cancel a day
//
// These mutate real orders and spend, so every command here is DRY-RUN BY
// DEFAULT: it prints the exact operation + variables it would POST and does
// nothing else. The mutation only fires when the caller passes --confirm.
// Under the verifier (PRINTING_PRESS_VERIFY=1) the commands always
// short-circuit before any network call, even with --confirm.
//
// Wire format matches the SPA exactly:
//
//	mutation ($input: <Op>Input!) { <op> (input: $input) { <returning> } }
//
// with {"variables": {"input": {...}}}. The client injects the x-csrf-token
// header for the /api/v2/graphql path automatically.
//
// This is a hand-authored file (no "Generated by ..." header) so
// `generate --force` preserves it.

