// mutateGraphQL runs a parameterized GraphQL mutation live against Forkable
// and returns the raw `data` object. Unlike fetchGraphQL (query-only, no
// variables), this sends {"query":..., "variables":{"input":...}} — the shape
// the SPA uses for every mutation. GraphQL-level errors arrive with HTTP 200
// and are surfaced as a Go error so callers never silently treat a rejected
// mutation as success.
func mutateGraphQL(ctx context.Context, flags *rootFlags, query string, variables map[string]any) (json.RawMessage, error) {
	c, err := flags.newClient()
	if err != nil {
		return nil, err
	}
	body := map[string]any{"query": query, "variables": variables}
	// Post (not PostQuery): this genuinely mutates remote state, so it must
	// ride the mutating verify-mode gate. Callers guard with dryRunOK/confirm
	// before reaching here, and IsVerifyEnv is re-checked below as defense in
	// depth. The CSRF header is injected by the client for the GraphQL path.
	raw, status, err := c.Post(ctx, forkableGraphQLPath, body)
	if err != nil {
		return nil, classifyAPIError(err, flags)
	}
	if status == 401 || status == 403 {
		return nil, fmt.Errorf("not authenticated (HTTP %d): run 'forkable-pp-cli auth login --chrome' after logging in to forkable.com in Chrome", status)
	}
	if status < 200 || status >= 300 {
		return nil, fmt.Errorf("forkable API returned HTTP %d", status)
	}
	var env gqlEnvelope
	if err := json.Unmarshal(raw, &env); err != nil {
		return nil, fmt.Errorf("parsing GraphQL response: %w", err)
	}
	if len(env.Errors) > 0 {
		return nil, fmt.Errorf("forkable GraphQL error: %s", env.Errors[0].Message)
	}
	// Top-level GraphQL errors (above) cover transport/schema-level
	// failures, but Forkable's mutations also arrive with HTTP 200 and
	// env.Errors empty when the mutation itself is rejected — the failure
	// surfaces only inside the single operation's own payload object, e.g.
	// {"replacePiece": {"delivery": null, "errors": ["..."]}}. Every
	// mutation built in this file requests "errors" in its selection set
	// (see the buildMutation call sites below), so this check applies
	// uniformly regardless of which operation ran. Without it, a rejected
	// write returns success here and emitMutationResult prints "Done."
	if err := payloadMutationErrors(env.Data); err != nil {
		return nil, err
	}
	return env.Data, nil
}

// payloadMutationErrors inspects a mutation's decoded `data` payload for a
// payload-level `errors` field and returns a non-nil error when it is
// present and non-empty. It does not assume how many top-level operation
// keys `data` has, or whether each error entry is a string or an object —
// different Forkable mutations use different shapes — so it treats any
// non-null, non-empty JSON array under "errors" as a rejected mutation. A
// missing "errors" field, or one that decodes to null or an empty array,
// is not an error.
func payloadMutationErrors(data json.RawMessage) error {
	var ops map[string]json.RawMessage
	if err := json.Unmarshal(data, &ops); err != nil {
		// Not a plain object we can inspect for payload errors; leave any
		// real problem for the caller's own use of data to surface.
		return nil
	}
	for _, opData := range ops {
		var payload struct {
			Errors json.RawMessage `json:"errors"`
		}
		if err := json.Unmarshal(opData, &payload); err != nil {
			continue
		}
		if len(payload.Errors) == 0 {
			continue
		}
		trimmed := strings.TrimSpace(string(payload.Errors))
		if trimmed == "" || trimmed == "null" {
			continue
		}
		var asArray []json.RawMessage
		if err := json.Unmarshal(payload.Errors, &asArray); err == nil && len(asArray) == 0 {
			continue
		}
		return fmt.Errorf("forkable mutation rejected the change: %s", trimmed)
	}
	return nil
}

// buildMutation renders the SPA's parameterized mutation shape. inputType is
// the GraphQL input type name (e.g. "ReplacePiece" -> "ReplacePieceInput!"),
// op is the field name, and returning is the selection set inside the payload.
func buildMutation(op, inputType, returning string) string {
	return fmt.Sprintf("mutation ($input: %sInput!) { %s (input: $input) { %s } }", inputType, op, returning)
}

// confirmOrPreview centralizes the dry-run / --confirm / verify-mode gate that
// every mutating command in this file shares. It returns true if the caller
// should proceed with the live mutation, or false (after printing a preview)
// if it should stop. The preview prints the human-readable action, the exact
// operation, and the JSON variables so an operator sees precisely what would
// be sent.
func confirmOrPreview(cmd *cobra.Command, flags *rootFlags, confirm bool, action, op string, variables map[string]any) bool {
	// Machine-output callers (--json/--agent, or piped stdout) must always get
	// valid JSON, including on the dry-run/preview and verify short-circuit
	// paths. Emitting prose here breaks agents and the dogfood json_fidelity
	// check.
	machineOut := flags.asJSON || flags.agent || !isTerminal(cmd.OutOrStdout())
	if dryRunOK(flags) || cliutil.IsVerifyEnv() {
		if machineOut {
			_ = printJSONFiltered(cmd.OutOrStdout(), map[string]any{
				"dry_run": true,
				"action":  action,
			}, flags)
		} else {
			fmt.Fprintf(cmd.OutOrStdout(), "would %s\n", action)
		}
		return false
	}
	if !confirm {
		if machineOut {
			_ = printJSONFiltered(cmd.OutOrStdout(), map[string]any{
				"dry_run":   true,
				"action":    action,
				"mutation":  op,
				"variables": variables,
				"hint":      "re-run with --confirm to apply",
			}, flags)
		} else {
			varJSON, _ := json.Marshal(variables)
			fmt.Fprintf(cmd.OutOrStdout(), "DRY RUN — would %s\n", action)
			fmt.Fprintf(cmd.OutOrStdout(), "  mutation: %s\n", op)
			fmt.Fprintf(cmd.OutOrStdout(), "  variables: %s\n", string(varJSON))
			fmt.Fprintln(cmd.OutOrStdout(), "Re-run with --confirm to place this change against your real Forkable account.")
		}
		return false
	}
	return true
}

// emitDryRunShortCircuit handles the early `--dry-run`/verify guard at the top
// of each write command's RunE, before required inputs are parsed. It emits
// valid JSON under --json/--agent/piped output and prose otherwise, so the
// dry-run path never breaks machine consumers.
func emitDryRunShortCircuit(cmd *cobra.Command, flags *rootFlags, action string) {
	if flags.asJSON || flags.agent || !isTerminal(cmd.OutOrStdout()) {
		_ = printJSONFiltered(cmd.OutOrStdout(), map[string]any{
			"dry_run": true,
			"action":  action,
		}, flags)
		return
	}
	fmt.Fprintf(cmd.OutOrStdout(), "would %s\n", action)
}

// emitMutationResult prints the mutation's data payload, honoring output flags.
func emitMutationResult(cmd *cobra.Command, flags *rootFlags, data json.RawMessage) error {
	if flags.asJSON || flags.agent || !isTerminal(cmd.OutOrStdout()) {
		var v any
		if err := json.Unmarshal(data, &v); err != nil {
			return printJSONFiltered(cmd.OutOrStdout(), map[string]any{"raw": string(data)}, flags)
		}
		return printJSONFiltered(cmd.OutOrStdout(), v, flags)
	}
	fmt.Fprintln(cmd.OutOrStdout(), "Done.")
	return nil
}

func parseInt64(s string) (int64, error) {
	return strconv.ParseInt(strings.TrimSpace(s), 10, 64)
}

// parseIDList parses a comma-separated list of int64 IDs.
func parseIDList(s string) ([]int64, error) {
	parts := strings.Split(s, ",")
	out := make([]int64, 0, len(parts))
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		id, err := parseInt64(p)
		if err != nil {
			return nil, fmt.Errorf("invalid id %q: %w", p, err)
		}
		out = append(out, id)
	}
	return out, nil
}

