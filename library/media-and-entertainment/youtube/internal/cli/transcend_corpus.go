func newCorpusSearchCmd(flags *rootFlags) *cobra.Command {
	var since string
	var sources string
	var limit int
	cmd := &cobra.Command{
		Use:   "search <query>",
		Short: "FTS5 union across video metadata, transcripts, and comments (zero quota)",
		Long: `Run an FTS5 query across the local YouTube corpus: video metadata
(title/description/tags), transcripts, and comments. Returns hits with a
` + "`kind`" + ` field naming the source (videos|transcripts|comments) so
agents can weight relevance.

Pre-populate the corpus with sync, transcripts get, and (for comments)
the youtube comments-list endpoint commands. With nothing synced, the
result set is empty.`,
		Example:     "  youtube-pp-cli corpus search \"AI safety\" --since 30d --json --select hits.video_id,hits.kind,hits.snippet --agent",
		Annotations: map[string]string{"mcp:read-only": "true"},
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 {
				return cmd.Help()
			}
			if dryRunOK(flags) {
				return nil
			}
			query := ftsQuote(strings.Join(args, " "))
			dbPath := defaultDBPath("youtube-pp-cli")
			db, err := store.OpenWithContext(cmd.Context(), dbPath)
			if err != nil {
				return fmt.Errorf("opening database: %w", err)
			}
			defer db.Close()
			if err := db.EnsureYouTubeExtras(cmd.Context()); err != nil {
				return err
			}
			cutoff := time.Time{}
			if since != "" {
				c, err := parseWindow(since)
				if err != nil {
					return err
				}
				cutoff = c
			}
			pickSources := map[string]bool{"videos": true, "transcripts": true, "comments": true}
			if sources != "" {
				pickSources = map[string]bool{}
				for _, s := range strings.Split(sources, ",") {
					pickSources[strings.TrimSpace(s)] = true
				}
			}
			hits := []map[string]any{}
			if pickSources["videos"] {
				vh, err := corpusSearchVideos(cmd.Context(), db.DB(), query, cutoff, limit)
				if err != nil {
					return err
				}
				hits = append(hits, vh...)
			}
			if pickSources["transcripts"] {
				th, err := corpusSearchTranscripts(cmd.Context(), db.DB(), query, limit)
				if err != nil {
					return err
				}
				hits = append(hits, th...)
			}
			if pickSources["comments"] {
				ch, err := corpusSearchComments(cmd.Context(), db.DB(), query, limit)
				if err != nil {
					return err
				}
				hits = append(hits, ch...)
			}
			if limit > 0 && len(hits) > limit {
				hits = hits[:limit]
			}
			env := map[string]any{
				"query":   query,
				"sources": sources,
				"hits":    hits,
				"count":   len(hits),
			}
			return printJSONFiltered(cmd.OutOrStdout(), env, flags)
		},
	}
	cmd.Flags().StringVar(&since, "since", "", "Only include videos published after this window (e.g. 7d, 30d)")
	cmd.Flags().StringVar(&sources, "sources", "videos,transcripts,comments", "Comma list of corpora to search")
	cmd.Flags().IntVar(&limit, "limit", 50, "Cap total hits returned")
	return cmd
}

func corpusSearchVideos(ctx context.Context, db *sql.DB, q string, cutoff time.Time, limit int) ([]map[string]any, error) {
	args := []any{q}
	clause := ""
	if !cutoff.IsZero() {
		clause = "AND v.published_at >= ?"
		args = append(args, cutoff.UTC().Format(time.RFC3339))
	}
	args = append(args, limit)
	rows, err := db.QueryContext(ctx, fmt.Sprintf(`
		SELECT f.video_id, f.channel_id, f.title, f.description, v.published_at
		  FROM yt_videos_fts f
		  JOIN yt_videos v ON v.video_id = f.video_id
		 WHERE yt_videos_fts MATCH ? %s
		 LIMIT ?`, clause), args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []map[string]any{}
	for rows.Next() {
		var vid, ch, title, desc, pub sql.NullString
		if err := rows.Scan(&vid, &ch, &title, &desc, &pub); err != nil {
			return nil, err
		}
		out = append(out, map[string]any{
			"kind":         "videos",
			"video_id":     vid.String,
			"channel_id":   ch.String,
			"title":        title.String,
			"snippet":      truncateSnippet(desc.String, 200),
			"published_at": pub.String,
		})
	}
	return out, nil
}

func corpusSearchTranscripts(ctx context.Context, db *sql.DB, q string, limit int) ([]map[string]any, error) {
	rows, err := db.QueryContext(ctx,
		`SELECT video_id, language, snippet(yt_transcripts_fts, 2, '<<', '>>', '...', 16)
		   FROM yt_transcripts_fts
		   WHERE yt_transcripts_fts MATCH ?
		   LIMIT ?`, q, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []map[string]any{}
	for rows.Next() {
		var vid, lang, snip sql.NullString
		if err := rows.Scan(&vid, &lang, &snip); err != nil {
			return nil, err
		}
		out = append(out, map[string]any{
			"kind":     "transcripts",
			"video_id": vid.String,
			"language": lang.String,
			"snippet":  snip.String,
		})
	}
	return out, nil
}

func corpusSearchComments(ctx context.Context, db *sql.DB, q string, limit int) ([]map[string]any, error) {
	rows, err := db.QueryContext(ctx,
		`SELECT comment_id, video_id, author_display_name, snippet(yt_comments_fts, 3, '<<', '>>', '...', 16)
		   FROM yt_comments_fts
		   WHERE yt_comments_fts MATCH ?
		   LIMIT ?`, q, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []map[string]any{}
	for rows.Next() {
		var cid, vid, author, snip sql.NullString
		if err := rows.Scan(&cid, &vid, &author, &snip); err != nil {
			return nil, err
		}
		out = append(out, map[string]any{
			"kind":       "comments",
			"comment_id": cid.String,
			"video_id":   vid.String,
			"author":     author.String,
			"snippet":    snip.String,
		})
	}
	return out, nil
}

func truncateSnippet(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}

// ftsQuote wraps a free-text user query for FTS5's MATCH operator. FTS5
// treats unquoted special characters (apostrophes, dashes, parens) as
// syntax — quoting the whole thing as a phrase keeps tokenization sane and
// blocks injection of column filters or operators. Inner double quotes are
// doubled per FTS5 escaping rules.
func ftsQuote(s string) string {
	s = strings.ReplaceAll(s, `"`, `""`)
	return `"` + s + `"`
}

// newDigestCmd: `digest <channel> --since 7d --keywords k1,k2`
//
// Joins yt_videos × yt_transcripts × yt_channels filtered by
// channel + publishedAt + transcript-FTS keyword set.
func newDigestCmd(flags *rootFlags) *cobra.Command {
	var since string
	var keywords string
	var limit int
	cmd := &cobra.Command{
		Use:   "digest <channel-id>",
		Short: "Channel digest: new uploads since N joined with transcript-FTS hits",
		Long: `For one channel, list uploads since --since (default 7d) joined with
transcript FTS matches for --keywords (CSV). Requires the channel's videos
and at least one transcript to be present in the local store; populate via
` + "`youtube-pp-cli sync`" + ` and ` + "`youtube-pp-cli transcripts get`" + `.`,
		Example:     "  youtube-pp-cli digest UCBJycsmduvYEL83R_U4JriQ --since 7d --keywords inference,RAG --json --agent",
		Annotations: map[string]string{"mcp:read-only": "true"},
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 {
				return cmd.Help()
			}
			if dryRunOK(flags) {
				return nil
			}
			channelID := args[0]
			cutoff, err := parseWindow(since)
			if err != nil {
				return err
			}
			dbPath := defaultDBPath("youtube-pp-cli")
			db, err := store.OpenWithContext(cmd.Context(), dbPath)
			if err != nil {
				return err
			}
			defer db.Close()
			if err := db.EnsureYouTubeExtras(cmd.Context()); err != nil {
				return err
			}

			// Fetch uploads
			rows, err := db.DB().QueryContext(cmd.Context(),
				`SELECT video_id, title, published_at, view_count
				   FROM yt_videos
				   WHERE channel_id = ? AND published_at >= ?
				   ORDER BY published_at DESC LIMIT ?`,
				channelID, cutoff.UTC().Format(time.RFC3339), limit)
			if err != nil {
				return err
			}
			defer rows.Close()
			type upload struct {
				VideoID        string           `json:"video_id"`
				Title          string           `json:"title"`
				PublishedAt    string           `json:"published_at"`
				ViewCount      int              `json:"view_count"`
				TranscriptHits []map[string]any `json:"transcript_hits,omitempty"`
				HasTranscript  bool             `json:"has_transcript"`
			}
			var uploads []upload
			for rows.Next() {
				var u upload
				var pub sql.NullString
				var views sql.NullInt64
				if err := rows.Scan(&u.VideoID, &u.Title, &pub, &views); err != nil {
					return err
				}
				u.PublishedAt = pub.String
				u.ViewCount = int(views.Int64)
				uploads = append(uploads, u)
			}

			// Match keywords against each video's transcript FTS row
			kwList := []string{}
			for _, k := range strings.Split(keywords, ",") {
				if k = strings.TrimSpace(k); k != "" {
					kwList = append(kwList, k)
				}
			}

			if len(kwList) > 0 {
				for i := range uploads {
					for _, kw := range kwList {
						hitRows, err := db.DB().QueryContext(cmd.Context(),
							`SELECT language, snippet(yt_transcripts_fts, 2, '<<', '>>', '...', 16)
							   FROM yt_transcripts_fts
							   WHERE video_id = ? AND yt_transcripts_fts MATCH ?
							   LIMIT 5`, uploads[i].VideoID, ftsQuote(kw))
						if err != nil {
							continue
						}
						for hitRows.Next() {
							var lang, snip sql.NullString
							if err := hitRows.Scan(&lang, &snip); err != nil {
								continue
							}
							uploads[i].TranscriptHits = append(uploads[i].TranscriptHits, map[string]any{
								"keyword":  kw,
								"language": lang.String,
								"snippet":  snip.String,
							})
						}
						hitRows.Close()
					}
					var n int
					_ = db.DB().QueryRowContext(cmd.Context(),
						`SELECT COUNT(*) FROM yt_transcripts WHERE video_id = ?`,
						uploads[i].VideoID).Scan(&n)
					uploads[i].HasTranscript = n > 0
				}
			}

			env := map[string]any{
				"channel_id":   channelID,
				"window_since": cutoff.UTC().Format(time.RFC3339),
				"keywords":     kwList,
				"uploads":      uploads,
				"upload_count": len(uploads),
			}
			return printJSONFiltered(cmd.OutOrStdout(), env, flags)
		},
	}
	cmd.Flags().StringVar(&since, "since", "7d", "Only include uploads after this window (e.g. 7d, 30d)")
	cmd.Flags().StringVar(&keywords, "keywords", "", "Comma list of FTS keywords to match per transcript")
	cmd.Flags().IntVar(&limit, "limit", 100, "Max uploads to return")
	return cmd
}

// newSyncChannelCmd: lightweight, YouTube-specific channel sync.
// Pulls channels.list (1u) + uploads playlistItems.list (1u/page) + videos.list batched (1u/50).
// Writes to yt_channels + yt_videos + yt_videos_fts and snapshots yt_video_snapshots for velocity tracking.
//
// Implementation note: this lives next to the transcendence commands because
// the generic sync is a no-op for YouTube without a starting parameter.
func newSyncChannelCmd(flags *rootFlags) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "sync-channel <channel-id>",
		Short: "Sync a channel's videos + stats into the local store (used by digest, velocity, corpus)",
		Long: `Pulls a YouTube channel's uploads playlist, batches videos.list calls
to fetch stats for each video, and writes everything to yt_channels,
yt_videos, yt_videos_fts, and yt_video_snapshots (for velocity tracking).

This is the YouTube-specific equivalent of the generic ` + "`sync`" + ` command,
which can't sync YouTube data without an explicit starting point.`,
		Example: "  youtube-pp-cli sync-channel UCBJycsmduvYEL83R_U4JriQ --max-videos 50",
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 {
				return cmd.Help()
			}
			if dryRunOK(flags) {
				return nil
			}
			channelID := args[0]
			maxVideos, _ := cmd.Flags().GetInt("max-videos")

			c, err := flags.newClient()
			if err != nil {
				return err
			}
			cfg, _ := config.Load(flags.configPath)
			dbPath := defaultDBPath("youtube-pp-cli")
			db, err := store.OpenWithContext(cmd.Context(), dbPath)
			if err != nil {
				return err
			}
			defer db.Close()
			if err := db.EnsureYouTubeExtras(cmd.Context()); err != nil {
				return err
			}

			// 1) channels.list
			chRaw, err := c.Get("/youtube/v3/channels", map[string]string{
				"part": "snippet,statistics,contentDetails",
				"id":   channelID,
			})
			if err != nil {
				return fmt.Errorf("channels.list: %w", err)
			}
			_ = db.LogQuota(cmd.Context(), hashKeyFromConfig(cfg), "sync-channel", "channels.list", quota.Cost("channels", "list"), 200, "")
			var chResp struct {
				Items []struct {
					ID      string `json:"id"`
					Snippet struct {
						Title       string `json:"title"`
						Description string `json:"description"`
						PublishedAt string `json:"publishedAt"`
					} `json:"snippet"`
					Statistics struct {
						SubscriberCount string `json:"subscriberCount"`
						ViewCount       string `json:"viewCount"`
						VideoCount      string `json:"videoCount"`
					} `json:"statistics"`
					ContentDetails struct {
						RelatedPlaylists struct {
							Uploads string `json:"uploads"`
						} `json:"relatedPlaylists"`
					} `json:"contentDetails"`
				} `json:"items"`
			}
			if err := json.Unmarshal(chRaw, &chResp); err != nil {
				return err
			}
			if len(chResp.Items) == 0 {
				return fmt.Errorf("channel %s not found", channelID)
			}
			ch := chResp.Items[0]
			subs, _ := parseInt(ch.Statistics.SubscriberCount)
			views, _ := parseInt(ch.Statistics.ViewCount)
			vids, _ := parseInt(ch.Statistics.VideoCount)
			if _, err := db.DB().ExecContext(cmd.Context(),
				`INSERT INTO yt_channels(channel_id,title,description,uploads_playlist_id,subscriber_count,view_count,video_count,published_at,updated_at)
				 VALUES(?,?,?,?,?,?,?,?,?)
				 ON CONFLICT(channel_id) DO UPDATE SET
				   title=excluded.title, description=excluded.description,
				   uploads_playlist_id=excluded.uploads_playlist_id,
				   subscriber_count=excluded.subscriber_count, view_count=excluded.view_count,
				   video_count=excluded.video_count, updated_at=excluded.updated_at`,
				ch.ID, ch.Snippet.Title, ch.Snippet.Description, ch.ContentDetails.RelatedPlaylists.Uploads,
				subs, views, vids, ch.Snippet.PublishedAt, time.Now().UTC().Format(time.RFC3339)); err != nil {
				return err
			}

			// 2) walk uploads playlist
			uploadsPlaylist := ch.ContentDetails.RelatedPlaylists.Uploads
			pageToken := ""
			collected := 0
			videoIDs := []string{}
			for collected < maxVideos {
				params := map[string]string{
					"part":       "snippet,contentDetails",
					"playlistId": uploadsPlaylist,
					"maxResults": "50",
				}
				if pageToken != "" {
					params["pageToken"] = pageToken
				}
				piRaw, err := c.Get("/youtube/v3/playlistItems", params)
				if err != nil {
					return fmt.Errorf("playlistItems.list: %w", err)
				}
				_ = db.LogQuota(cmd.Context(), hashKeyFromConfig(cfg), "sync-channel", "playlistItems.list", quota.Cost("playlistItems", "list"), 200, "")
				var piResp struct {
					NextPageToken string `json:"nextPageToken"`
					Items         []struct {
						ContentDetails struct {
							VideoID string `json:"videoId"`
						} `json:"contentDetails"`
					} `json:"items"`
				}
				if err := json.Unmarshal(piRaw, &piResp); err != nil {
					return err
				}
				for _, it := range piResp.Items {
					videoIDs = append(videoIDs, it.ContentDetails.VideoID)
					collected++
					if collected >= maxVideos {
						break
					}
				}
				if piResp.NextPageToken == "" {
					break
				}
				pageToken = piResp.NextPageToken
			}

			// 3) videos.list batched (50 per call)
			vidsCount, err := batchFetchVideos(cmd.Context(), c, db, cfg, videoIDs)
			if err != nil {
				return err
			}

			env := map[string]any{
				"channel_id":       channelID,
				"channel_title":    ch.Snippet.Title,
				"uploads_synced":   vidsCount,
				"uploads_playlist": uploadsPlaylist,
			}
			return printJSONFiltered(cmd.OutOrStdout(), env, flags)
		},
	}
	cmd.Flags().Int("max-videos", 50, "Max uploads to fetch (1 quota unit per 50)")
	return cmd
}

// batchFetchVideos pulls the videos.list metadata for a slice of IDs in
// 50-id batches, writes them to yt_videos + yt_videos_fts + yt_video_snapshots,
// and returns the count of videos actually persisted.
func batchFetchVideos(ctx context.Context, c interface {
	Get(string, map[string]string) (json.RawMessage, error)
}, db *store.Store, cfg *config.Config, ids []string) (int, error) {
	saved := 0
	for i := 0; i < len(ids); i += 50 {
		end := i + 50
		if end > len(ids) {
			end = len(ids)
		}
		batch := ids[i:end]
		raw, err := c.Get("/youtube/v3/videos", map[string]string{
			"part": "snippet,statistics,contentDetails",
			"id":   strings.Join(batch, ","),
		})
		if err != nil {
			return saved, fmt.Errorf("videos.list batch: %w", err)
		}
		_ = db.LogQuota(ctx, hashKeyFromConfig(cfg), "sync-channel", "videos.list", quota.Cost("videos", "list"), 200, fmt.Sprintf("batch=%d", len(batch)))
		var vidResp struct {
			Items []struct {
				ID      string `json:"id"`
				Snippet struct {
					ChannelID   string   `json:"channelId"`
					Title       string   `json:"title"`
					Description string   `json:"description"`
					PublishedAt string   `json:"publishedAt"`
					Tags        []string `json:"tags"`
				} `json:"snippet"`
				Statistics struct {
					ViewCount    string `json:"viewCount"`
					LikeCount    string `json:"likeCount"`
					CommentCount string `json:"commentCount"`
				} `json:"statistics"`
				ContentDetails struct {
					Duration string `json:"duration"`
				} `json:"contentDetails"`
			} `json:"items"`
		}
		if err := json.Unmarshal(raw, &vidResp); err != nil {
			return saved, err
		}
		now := time.Now().UTC().Format(time.RFC3339)
		for _, v := range vidResp.Items {
			views, _ := parseInt(v.Statistics.ViewCount)
			likes, _ := parseInt(v.Statistics.LikeCount)
			comments, _ := parseInt(v.Statistics.CommentCount)
			dur := iso8601DurationToSeconds(v.ContentDetails.Duration)
			tags := strings.Join(v.Snippet.Tags, ", ")
			if _, err := db.DB().ExecContext(ctx,
				`INSERT INTO yt_videos(video_id,channel_id,title,description,published_at,duration_seconds,view_count,like_count,comment_count,tags,updated_at)
				 VALUES(?,?,?,?,?,?,?,?,?,?,?)
				 ON CONFLICT(video_id) DO UPDATE SET
				   title=excluded.title, description=excluded.description,
				   duration_seconds=excluded.duration_seconds,
				   view_count=excluded.view_count, like_count=excluded.like_count,
				   comment_count=excluded.comment_count, tags=excluded.tags,
				   updated_at=excluded.updated_at`,
				v.ID, v.Snippet.ChannelID, v.Snippet.Title, v.Snippet.Description, v.Snippet.PublishedAt,
				dur, views, likes, comments, tags, now); err != nil {
				return saved, err
			}
			// FTS row replace
			_, _ = db.DB().ExecContext(ctx, `DELETE FROM yt_videos_fts WHERE video_id = ?`, v.ID)
			_, _ = db.DB().ExecContext(ctx,
				`INSERT INTO yt_videos_fts(video_id, channel_id, title, description, tags) VALUES(?,?,?,?,?)`,
				v.ID, v.Snippet.ChannelID, v.Snippet.Title, v.Snippet.Description, tags)
			// Snapshot for velocity
			_, _ = db.DB().ExecContext(ctx,
				`INSERT INTO yt_video_snapshots(video_id, captured_at, channel_id, title, published_at, view_count, like_count, comment_count, duration_seconds)
				 VALUES(?,?,?,?,?,?,?,?,?)
				 ON CONFLICT(video_id, captured_at) DO NOTHING`,
				v.ID, now, v.Snippet.ChannelID, v.Snippet.Title, v.Snippet.PublishedAt, views, likes, comments, dur)
			saved++
		}
	}
	return saved, nil
}

func parseInt(s string) (int, error) {
	if s == "" {
		return 0, nil
	}
	n := 0
	for _, c := range s {
		if c < '0' || c > '9' {
			return n, fmt.Errorf("bad int %q", s)
		}
		n = n*10 + int(c-'0')
	}
	return n, nil
}

// iso8601DurationToSeconds parses a duration string like PT4M13S into 253.
// Best-effort: returns 0 on parse failure.
func iso8601DurationToSeconds(s string) int {
	if !strings.HasPrefix(s, "PT") {
		return 0
	}
	s = s[2:]
	total := 0
	num := 0
	for _, c := range s {
		switch {
		case c >= '0' && c <= '9':
			num = num*10 + int(c-'0')
		case c == 'H':
			total += num * 3600
			num = 0
		case c == 'M':
			total += num * 60
			num = 0
		case c == 'S':
			total += num
			num = 0
		}
	}
	return total
}

