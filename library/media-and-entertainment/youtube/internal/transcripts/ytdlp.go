// Package transcripts shells out to yt-dlp to fetch YouTube transcripts
// without burning Data API quota. yt-dlp is a system dependency; see doctor
// for the install hint.
package transcripts

import (
	"bufio"
	"context"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
)

// Result holds a fetched transcript.
type Result struct {
	VideoID       string `json:"video_id"`
	Language      string `json:"language"`
	AutoGenerated bool   `json:"auto_generated"`
	Format        string `json:"format"`
	Content       string `json:"content"`
	FetchedAt     string `json:"fetched_at"`
}

// EnsureYTDLP returns the resolved path to yt-dlp or an error with an
// actionable install hint.
func EnsureYTDLP() (string, error) {
	p, err := exec.LookPath("yt-dlp")
	if err != nil {
		return "", fmt.Errorf("yt-dlp not found on PATH; install with `brew install yt-dlp` (macOS) or `pip install yt-dlp`")
	}
	return p, nil
}

// dumpJSON wraps `yt-dlp --skip-download --dump-json --no-warnings <url>` so
// callers can inspect available subtitle tracks before deciding what to fetch.
func dumpJSON(ctx context.Context, ytdlp, videoID string) (map[string]any, error) {
	url := "https://www.youtube.com/watch?v=" + videoID
	cmd := exec.CommandContext(ctx, ytdlp,
		"--skip-download", "--dump-json", "--no-warnings", "--no-playlist", url)
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("yt-dlp dump-json: %w", err)
	}
	var meta map[string]any
	if err := json.Unmarshal(out, &meta); err != nil {
		return nil, fmt.Errorf("parsing yt-dlp metadata: %w", err)
	}
	return meta, nil
}

// AvailableLanguages returns the set of subtitle/auto-caption language codes
// for a video, with auto-captions suffixed `:auto`.
func AvailableLanguages(ctx context.Context, videoID string) ([]string, error) {
	ytdlp, err := EnsureYTDLP()
	if err != nil {
		return nil, err
	}
	meta, err := dumpJSON(ctx, ytdlp, videoID)
	if err != nil {
		return nil, err
	}
	out := []string{}
	if subs, ok := meta["subtitles"].(map[string]any); ok {
		for k := range subs {
			out = append(out, k)
		}
	}
	if auto, ok := meta["automatic_captions"].(map[string]any); ok {
		for k := range auto {
			out = append(out, k+":auto")
		}
	}
	sort.Strings(out)
	return out, nil
}

// Fetch downloads a transcript for a YouTube video. lang="" picks the first
// available manual track, falling back to auto-generated if none. Returns the
// raw VTT content with cue boundaries preserved (the yt_transcripts table
// stores it as-is and FTS strips timing).
func Fetch(ctx context.Context, videoID, lang string) (*Result, error) {
	ytdlp, err := EnsureYTDLP()
	if err != nil {
		return nil, err
	}
	tmpdir, err := os.MkdirTemp("", "yt-transcripts-*")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmpdir)

	url := "https://www.youtube.com/watch?v=" + videoID
	args := []string{
		"--skip-download",
		"--no-warnings",
		"--no-playlist",
		"--write-subs",
		"--write-auto-subs",
		"--sub-format", "vtt",
		"-o", filepath.Join(tmpdir, "%(id)s.%(ext)s"),
	}
	wantLang := lang
	autoOnly := false
	if strings.HasSuffix(lang, ":auto") {
		wantLang = strings.TrimSuffix(lang, ":auto")
		autoOnly = true
	}
	if wantLang != "" {
		args = append(args, "--sub-langs", wantLang)
	} else {
		args = append(args, "--sub-langs", "en.*,en")
	}
	args = append(args, url)
	cmd := exec.CommandContext(ctx, ytdlp, args...)
	if out, err := cmd.CombinedOutput(); err != nil {
		return nil, fmt.Errorf("yt-dlp transcript fetch: %w (output: %s)", err, strings.TrimSpace(string(out)))
	}

	entries, err := os.ReadDir(tmpdir)
	if err != nil {
		return nil, err
	}
	var pickPath, pickLang string
	pickAuto := false
	for _, e := range entries {
		name := e.Name()
		if !strings.HasSuffix(name, ".vtt") {
			continue
		}
		base := strings.TrimSuffix(name, ".vtt")
		dot := strings.LastIndex(base, ".")
		if dot < 0 {
			continue
		}
		// Prefer manual over auto unless autoOnly. yt-dlp uses `videoid.lang.vtt`
		// for both; auto-generated tracks share the same naming. We check by
		// reading the file header for the auto marker.
		path := filepath.Join(tmpdir, name)
		curLang := base[dot+1:]
		isAuto := looksAutoGenerated(path)
		if pickPath == "" || (!autoOnly && pickAuto && !isAuto) {
			pickPath = path
			pickLang = curLang
			pickAuto = isAuto
		}
	}
	if pickPath == "" {
		return nil, fmt.Errorf("no transcript found for video %s (lang=%s)", videoID, lang)
	}
	content, err := os.ReadFile(pickPath)
	if err != nil {
		return nil, err
	}
	return &Result{
		VideoID:       videoID,
		Language:      pickLang,
		AutoGenerated: pickAuto,
		Format:        "vtt",
		Content:       string(content),
		FetchedAt:     time.Now().UTC().Format(time.RFC3339),
	}, nil
}

// PlainText strips VTT/SRT timing cues from `Content` and returns the
// plain-text transcript suitable for FTS or display.
func (r *Result) PlainText() string {
	if r == nil || r.Content == "" {
		return ""
	}
	scanner := bufio.NewScanner(strings.NewReader(r.Content))
	scanner.Buffer(make([]byte, 0, 1024*1024), 8*1024*1024)
	cueLine := regexp.MustCompile(`^\d{2}:\d{2}:\d{2}\.\d{3} --> \d{2}:\d{2}:\d{2}\.\d{3}`)
	tagStrip := regexp.MustCompile(`<[^>]+>`)
	timestampInline := regexp.MustCompile(`<\d{2}:\d{2}:\d{2}\.\d{3}>`)
	var b strings.Builder
	prev := ""
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || line == "WEBVTT" {
			continue
		}
		if cueLine.MatchString(line) {
			continue
		}
		if strings.HasPrefix(line, "Kind:") || strings.HasPrefix(line, "Language:") || strings.HasPrefix(line, "NOTE") {
			continue
		}
		line = timestampInline.ReplaceAllString(line, "")
		line = tagStrip.ReplaceAllString(line, "")
		line = strings.TrimSpace(line)
		if line == "" || line == prev {
			continue
		}
		b.WriteString(line)
		b.WriteByte('\n')
		prev = line
	}
	return strings.TrimSpace(b.String())
}

func looksAutoGenerated(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	count := 0
	for sc.Scan() && count < 10 {
		l := sc.Text()
		if strings.Contains(strings.ToLower(l), "kind: captions") {
			return true
		}
		count++
	}
	return false
}
