package cli

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/tabwriter"

	"github.com/spf13/cobra"
)

type iamBinding struct {
	Role   string `json:"role"`
	Member string `json:"member"`
}

type iamDiffView struct {
	Service   string       `json:"service"`
	Added     []iamBinding `json:"added"`
	Removed   []iamBinding `json:"removed"`
	Unchanged int          `json:"unchanged"`
}

func newNovelIamDiffCmd(flags *rootFlags) *cobra.Command {
	var flagService string
	var flagSnapshot string

	cmd := &cobra.Command{
		Use:   "diff",
		Short: "Compare the current IAM policy of a service against a saved snapshot to detect added or removed bindings.",
		Long:  "Diffs the current IAM policy against a JSON snapshot previously saved with `services get-iam-policy`. Surfaces added and removed role/member bindings. Snapshot must be generated by the same CLI to ensure format parity.",
		Example: strings.Trim(`
  google-cloud-run-pp-cli iam diff --service projects/my-proj/locations/us-central1/services/my-svc --snapshot ./iam-baseline.json
  google-cloud-run-pp-cli iam diff --service projects/my-proj/locations/us-central1/services/my-svc --snapshot ./iam-baseline.json --json`, "\n"),
		Annotations: map[string]string{"mcp:read-only": "true"},
		RunE: func(cmd *cobra.Command, args []string) error {
			if flagService == "" && cmd.Flags().NFlag() == 0 {
				return cmd.Help()
			}
			if dryRunOK(flags) {
				fmt.Fprintf(cmd.OutOrStdout(), "would diff IAM policy for %s against %s\n", flagService, flagSnapshot)
				return nil
			}
			if flagService == "" {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("--service is required"))
			}
			if flagSnapshot == "" {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("--snapshot is required (path to JSON file from 'services get-iam-policy')"))
			}

			// Read snapshot from disk. filepath.Clean normalizes the path before reading.
			cleanSnap := filepath.Clean(flagSnapshot)
			snapBytes, err := os.ReadFile(cleanSnap)
			if err != nil {
				return fmt.Errorf("reading snapshot %s: %w", cleanSnap, err)
			}

			c, err := flags.newClient()
			if err != nil {
				return err
			}
			ctx := context.Background()

			iamData, err := c.Get(ctx, "/v2/"+flagService+":getIamPolicy", nil)
			if err != nil {
				return classifyAPIError(err, flags)
			}

			type iamPolicy struct {
				Bindings []struct {
					Role    string   `json:"role"`
					Members []string `json:"members"`
				} `json:"bindings"`
			}

			var current, snapshot iamPolicy
			if err := json.Unmarshal(iamData, &current); err != nil {
				return fmt.Errorf("parsing current policy: %w", err)
			}
			// Snapshot may be wrapped in a provenance envelope; try top-level bindings first
			if err := json.Unmarshal(snapBytes, &snapshot); err != nil {
				return fmt.Errorf("parsing snapshot: %w", err)
			}
			// If snapshot has no bindings at top level, try unwrapping data field
			if len(snapshot.Bindings) == 0 {
				var wrapped struct {
					Data iamPolicy `json:"data"`
				}
				if json.Unmarshal(snapBytes, &wrapped) == nil && len(wrapped.Data.Bindings) > 0 {
					snapshot = wrapped.Data
				}
			}

			// Flatten both to sets of (role, member) pairs
			type bindingKey struct{ role, member string }
			currentSet := make(map[bindingKey]bool)
			snapshotSet := make(map[bindingKey]bool)

			for _, b := range current.Bindings {
				for _, m := range b.Members {
					currentSet[bindingKey{b.Role, m}] = true
				}
			}
			for _, b := range snapshot.Bindings {
				for _, m := range b.Members {
					snapshotSet[bindingKey{b.Role, m}] = true
				}
			}

			var added, removed []iamBinding
			unchanged := 0

			for k := range currentSet {
				if snapshotSet[k] {
					unchanged++
				} else {
					added = append(added, iamBinding{Role: k.role, Member: k.member})
				}
			}
			for k := range snapshotSet {
				if !currentSet[k] {
					removed = append(removed, iamBinding{Role: k.role, Member: k.member})
				}
			}

			view := iamDiffView{
				Service:   shortName(flagService),
				Added:     added,
				Removed:   removed,
				Unchanged: unchanged,
			}
			if added == nil {
				view.Added = []iamBinding{}
			}
			if removed == nil {
				view.Removed = []iamBinding{}
			}

			if flags.asJSON || (!isTerminal(cmd.OutOrStdout()) && !flags.csv && !flags.quiet && !flags.plain) {
				return printJSONFiltered(cmd.OutOrStdout(), view, flags)
			}

			if len(added) == 0 && len(removed) == 0 {
				fmt.Fprintln(cmd.OutOrStdout(), "no IAM changes detected")
				return nil
			}
			tw := tabwriter.NewWriter(cmd.OutOrStdout(), 0, 0, 2, ' ', 0)
			fmt.Fprintln(tw, "STATUS\tROLE\tMEMBER")
			for _, b := range added {
				fmt.Fprintf(tw, "+ added\t%s\t%s\n", b.Role, b.Member)
			}
			for _, b := range removed {
				fmt.Fprintf(tw, "- removed\t%s\t%s\n", b.Role, b.Member)
			}
			tw.Flush()
			fmt.Fprintf(cmd.OutOrStdout(), "\n%d added, %d removed, %d unchanged\n", len(added), len(removed), unchanged)
			return nil
		},
	}

	cmd.Flags().StringVar(&flagService, "service", "", "Full resource name of the service (projects/{project}/locations/{region}/services/{service})")
	cmd.Flags().StringVar(&flagSnapshot, "snapshot", "", "Path to a JSON IAM policy snapshot (from 'services get-iam-policy --json')")
	return cmd
}
